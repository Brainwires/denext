  assertMatch(down.lines.join("\n"), /unreachable/);
  const none = fakeIo({ rows: [] });
  assertEquals(await runStack(ctx("/p", ["health"]), none.io), 1);
  assertEquals(none.lines[0], "The stack is not running (denext stack up).");
