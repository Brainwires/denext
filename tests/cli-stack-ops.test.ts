async function project(env = ENV, mode = 0o600): Promise<string> {
  const root = await Deno.makeTempDir({ prefix: "dnx-stack-ops-" });
  await Deno.writeTextFile(join(root, ".env"), env);
  if (posix) await Deno.chmod(join(root, ".env"), mode);
  return root;
}

/** Every line but the ones naming `changed` is byte-identical. */
function assertOnlyChanged(before: string, after: string, changed: string[]): void {
  const keep = (text: string) =>
    text.split("\n").filter((l) => !changed.some((n) => new RegExp(`^(export )?${n}=`).test(l)));
  assertEquals(keep(after), keep(before));
}

