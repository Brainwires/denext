/** A pipe that answers like the db container: pg_dump bytes, SQL rows, a table count. */
function dbPipe(tables = "0") {
  return ({ args, options }: PipeCall) => {
    const cmd = args.join(" ");
    if (options.outputFile) {
      const body = cmd.includes("pg_dump")
        ? "PGDMP fake dump"
        : `-- ${options.input?.slice(0, 20)}`;
      Deno.writeTextFileSync(options.outputFile, body);
      return { code: 0 };
    }
    if (options.input?.includes("count(*)")) return { code: 0, stdout: `${tables}\n` };
    return { code: 0 };
  };
}

/** `docker compose cp` out of MinIO writes an object into the target. */
function cpOut(args: string[]) {
  if (args.includes("cp") && args.at(-2)?.startsWith("minio:")) {
    Deno.mkdirSync(join(args.at(-1)!, "avatars"), { recursive: true });
    Deno.writeTextFileSync(join(args.at(-1)!, "avatars", "a.png"), "png");
  }
  return { code: 0 };
}

Deno.test("stack backup: a dump by default, a full tar with a manifest; restore runs its order", async () => {
  const root = await project("S3_BUCKET=media\nPOSTGRES_DB=app\n");
  try {
    const plain = fakeIo({ pipe: dbPipe() });
    assertEquals(await runStack(ctx(root, ["backup", "db.dump"]), plain.io), 0);
    assertEquals(await Deno.readTextFile(join(root, "db.dump")), "PGDMP fake dump");
    if (posix) assertEquals((await Deno.stat(join(root, "db.dump"))).mode! & 0o777, 0o600);
    assertEquals(await backupKind(join(root, "db.dump")), "dump");
    assertEquals(await runStack(ctx(root, ["backup", "db.dump"]), plain.io), 1, "never overwrites");

    const full = fakeIo({ pipe: dbPipe(), docker: cpOut });
    assertEquals(await runStack(ctx(root, ["backup"], { full: true }), full.io), 0);
    const backups = [...Deno.readDirSync(join(root, ".denext", "backups"))].map((e) => e.name);
    assertEquals(backups.length, 1);
    assertMatch(backups[0], /^stack-.*\.tar\.gz$/);
    const archive = join(root, ".denext", "backups", backups[0]);
    assertEquals(await backupKind(archive), "full");
    const mirror = full.pipes.find((p) => p.args.join(" ").includes("mc mirror"))!;
    assertEquals(mirror.args.at(-1), "media", "the bucket is an argument, not script text");

    const restore = fakeIo({ pipe: dbPipe(), docker: () => ({ code: 0 }) });
    assertEquals(await runStack(ctx(root, ["restore", archive]), restore.io), 0);
    const order = restore.lines.filter((l) => l.startsWith("  restored ")).map((l) => l.slice(11));
    assertEquals(order, [...RESTORE_STEPS]);
    const docker = restore.calls.map((c) => c.slice(3).join(" "));
    const stop = docker.indexOf("stop web");
    const start = docker.indexOf("start web");
    const pgRestore = restore.pipes.findIndex((p) => p.args.join(" ").includes("pg_restore"));
    assert(stop !== -1 && start > stop && pgRestore !== -1, "the app is stopped around it");
    // The extracted directory is a host path (`C:\…\storage/.` on Windows, which docker takes).
    assert(docker.some((c) => /^cp .*[\\/]storage\/\. minio:\/tmp\/denext-restore$/.test(c)));
  } finally {
    await Deno.remove(root, { recursive: true });
  }
});

