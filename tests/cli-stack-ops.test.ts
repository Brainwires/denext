interface PipeCall {
  args: string[];
  options: PipeOptions;
}

/** A scripted Docker + terminal; `pipe` and `docker` answer through the handlers. */
function fakeIo(options: {
  rows?: PsRow[];
  pipe?: (call: PipeCall) => Promise<{ code: number; stdout?: string; stderr?: string }> | {
    code: number;
    stdout?: string;
    stderr?: string;
  };
  docker?: (args: string[]) => Promise<{ code: number; stderr?: string }> | {
    code: number;
    stderr?: string;
  };
  terminal?: boolean;
  confirm?: boolean;
  secrets?: string[];
  fetch?: (url: string) => Promise<Response>;
  freeBytes?: number;
} = {}) {
  const calls: string[][] = [];
  const pipes: PipeCall[] = [];
  const lines: string[] = [];
  const errors: string[] = [];
  const questions: string[] = [];
  const secrets = [...options.secrets ?? []];
  const io: StackIo = {
    docker: async (args) => {
      calls.push(args);
      if (args.includes("ps")) {
        return { code: 0, stdout: JSON.stringify(options.rows ?? RUNNING), stderr: "" };
      }
      const out = await options.docker?.(args) ?? { code: 0 };
      return { code: out.code, stdout: "", stderr: out.stderr ?? "" };
    },
    generate: () => Promise.resolve(),
    log: (l) => void lines.push(l),
    error: (l) => void errors.push(l),
    pipe: async (args, _cwd, opts) => {
      const call = { args, options: opts };
      pipes.push(call);
      const out = await options.pipe?.(call) ?? { code: 0 };
      return { code: out.code, stdout: out.stdout ?? "", stderr: out.stderr ?? "" };
    },
    stream: (args, _cwd, onLine) => {
      calls.push(args);
      for (
        const l of [
          "db-1   | 2026-10-14 LOG:  checkpoint starting",
          "db-1   | 2026-10-14 ERROR:  relation missing",
          'web-1  | {"level":"warn","msg":"slow request /api"}',
          "web-1  | plain line about /api",
        ]
      ) onLine(l);
      return Promise.resolve(0);
    },
    isTerminal: () => options.terminal ?? false,
    confirm: (q) => {
      questions.push(q);
      return Promise.resolve(options.confirm ?? false);
    },
    readSecret: () => {
      const next = secrets.shift();
      return next === undefined ? Promise.reject(new Error("no password on stdin")) : (
        Promise.resolve(next)
      );
    },
    fetch: options.fetch ??
      (() => Promise.resolve(Response.json({ status: "ok", checks: { database: "ok" } }))),
    sleep: () => Promise.reject(new Error("stop watching")),
    freeBytes: () => Promise.resolve(options.freeBytes),
  };
  return { io, calls, pipes, lines, errors, questions };
}

