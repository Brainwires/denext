Deno.test(".env edit: only the changed values move; comments, layout and CRLF are kept", () => {
  const text = "# c\r\n\r\nA=1\r\nexport B=2 # note\r\nA=dup\r\nC='q'\r\n";
  const out = setEnvValues(text, { A: "x", B: "y y", D: "new" }, { D: "Added." });
  assertEquals(
    out,
    "# c\r\n\r\nA=x\r\nexport B='y y' # note\r\nA=x\r\nC='q'\r\n# Added.\r\nD=new\r\n",
  );
  assertEquals(setEnvValues("A=1", { B: "2" }), "A=1\nB=2\n", "a missing final newline is added");
  assertEquals(setEnvValues("", { B: "2" }), "B=2\n");
  assertEquals(setEnvValues(ENV, {}), ENV, "no change is a byte-identical round trip");
  assertEquals(formatEnvValue("abc-123_./:+=@,~"), "abc-123_./:+=@,~");
  assertEquals(formatEnvValue('[{"a":1}]'), `'[{"a":1}]'`);
  assertEquals(formatEnvValue("has $dollar"), "'has $dollar'");
  assertThrows(() => formatEnvValue("it's"), Error, "single quote");
  assertThrows(() => formatEnvValue("a\nb"), Error, "newline");
  assertThrows(() => setEnvValues("", { "BAD-NAME": "x" }), Error, "invalid variable name");
});

Deno.test(".env write: atomic, keeps the file's mode, follows a symlink, 0600 when new", async () => {
  const root = await project(ENV, 0o640);
  try {
    const path = join(root, ".env");
    await writeFileAtomic(path, "A=1\n");
    assertEquals(await Deno.readTextFile(path), "A=1\n");
    if (posix) {
      assertEquals((await Deno.stat(path)).mode! & 0o777, 0o640);
      await writeFileAtomic(join(root, "fresh"), "x");
      assertEquals((await Deno.stat(join(root, "fresh"))).mode! & 0o777, 0o600);
      await Deno.symlink(path, join(root, "link"));
      await writeFileAtomic(join(root, "link"), "B=2\n");
      assert((await Deno.lstat(join(root, "link"))).isSymlink, "the link stays a link");
      assertEquals(await Deno.readTextFile(path), "B=2\n");
    }
    const staged = await prepareWrite(path, "C=3\n");
    await staged.discard();
    assertEquals(await Deno.readTextFile(path), posix ? "B=2\n" : "A=1\n");
    const left = [...Deno.readDirSync(root)].map((e) => e.name).filter((n) => n.endsWith(".tmp"));
    assertEquals(left, [], "no temp file left behind");
  } finally {
    await Deno.remove(root, { recursive: true });
  }
});

