Deno.test("generate ci: the project's check + build tasks, Deno pinned, valid YAML", async () => {
  const dir = await project({
    "deno.json": '{ "tasks": { "check": "deno fmt --check", "build": "denext build ." } }',
  });
  try {
    const { written } = await generateArtifact(dir, "ci", "");
    assertEquals(written, [join(dir, ".github", "workflows", "ci.yml")]);
    const text = await Deno.readTextFile(written[0]);
    assert(text.startsWith("# Generated by `denext generate ci`"));
    const doc = parseYaml(text) as {
      jobs: { check: { steps: { run?: string; with?: Record<string, unknown> }[] } };
    };
    const steps = doc.jobs.check.steps;
    assertEquals(steps.filter((s) => s.run).map((s) => s.run), [
      "deno task check",
      "deno task build",
    ]);
    assertEquals(steps[1].with?.["deno-version"], `v${denoReleaseVersion(Deno.version.deno)}`);
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});

