/** Ask the child's handler, in-process, on `sql`. */
async function ask<K extends keyof DbReplies>(
  sql: SqlClient,
  request: DbRequest,
  projectDir = "/nowhere",
  readOnly = false,
): Promise<DbSuccess<K>> {
  const reply = await handleDbRequest({ readOnly, request }, {
    projectDir,
    connect: () => ({ sql, display: "test", source: "env", close: () => Promise.resolve() }),
  }) as DbReply<K>;
  if (!reply.ok) throw new Error(`${request.op}: ${reply.code}: ${reply.reason}`);
  return reply;
}

/** The same, expecting a failure. */
async function fails(sql: SqlClient, request: DbRequest): Promise<DbFailure> {
  const reply = await handleDbRequest({ readOnly: false, request }, {
    projectDir: "/nowhere",
    connect: () => ({ sql, display: "test", source: "env", close: () => Promise.resolve() }),
  });
  assert(!reply.ok, `${request.op} should fail`);
  return reply as DbFailure;
}

/** Walk every page of `notes`, returning the ids in visit order. */
async function walk(
  sql: SqlClient,
  options: { sort?: string; direction?: "asc" | "desc" } = {},
): Promise<{ id: string; title: string | null }[]> {
  const out: { id: string; title: string | null }[] = [];
  let after: (string | null)[] | undefined;
  for (let guard = 0; guard < 20; guard++) {
    const page = await ask<"rows">(sql, {
      op: "rows",
      schema: "public",
      table: "notes",
      ...(options.sort ? { sort: options.sort } : {}),
      direction: options.direction ?? "asc",
      ...(after ? { after } : {}),
    });
    out.push(...page.rows.map((r) => ({ id: r.id!, title: r.title })));
    if (!page.next) return out;
    after = page.next;
  }
  throw new Error("paging did not end");
}

/** The schema and data: 120 notes (every 7th title NULL), owned by A or B, under RLS. */
async function seed(sql: SqlClient): Promise<void> {
  await ensureRlsMigrated(sql);
  await sql.unsafe(`
    create table notes (
      id bigint generated by default as identity primary key,
      owner uuid not null,
      title text,
      created timestamptz not null default now()
    );
    insert into notes (owner, title)
      select case when g % 2 = 0 then '${A}'::uuid else '${B}'::uuid end,
             case when g % 7 = 0 then null else 'note ' || lpad(g::text, 3, '0') end
      from generate_series(1, 120) g;
    create view note_titles as select id, title from notes;
    alter table notes enable row level security;
    create policy "read own notes" on notes for select to authenticated using (auth.uid() = owner);
    grant select on notes to authenticated, anon;
    create table keyless (v text);
  `).simple!();
}

Deno.test({
  name: `db-admin on a real Postgres: catalog, paging, RLS preview, writes, guards${label}`,
  ignore: reason !== undefined,
  sanitizeResources: false,
  async fn() {
    const env = await environment();
    try {
      const sql = env.app;
      await seed(sql);

      const overview = await ask<"overview">(sql, { op: "overview" });
      const notes = overview.tables.find((t) => t.name === "notes")!;
      assertEquals([notes.kind, notes.rls, notes.hasPrimaryKey], ["table", true, true]);
      assertEquals(overview.tables.find((t) => t.name === "note_titles")?.kind, "view");
      assertEquals(overview.tables.find((t) => t.name === "keyless")?.hasPrimaryKey, false);

      const { table } = await ask<"table">(sql, { op: "table", schema: "public", table: "notes" });
      assertEquals(table.primaryKey, ["id"]);
      assertEquals(table.columns.map((c) => [c.name, c.castType]), [
        ["id", "bigint"],
        ["owner", "uuid"],
        ["title", "text"],
        ["created", "timestamp with time zone"],
      ]);
      assertEquals(table.columns[0].identity, "by default");
      assertEquals(table.policies.map((p) => p.name), ["read own notes"]);
      assert(table.indexes.some((i) => i.name === "notes_pkey"));

      // Keyset paging visits each row once, in order — by key, and by a nullable column both ways.
      const byKey = await walk(sql);
      assertEquals(byKey.map((r) => Number(r.id)), Array.from({ length: 120 }, (_, i) => i + 1));
      for (const direction of ["asc", "desc"] as const) {
        const byTitle = await walk(sql, { sort: "title", direction });
        assertEquals(new Set(byTitle.map((r) => r.id)).size, 120, direction);
        const titles = byTitle.map((r) => r.title);
        const firstNull = titles.indexOf(null);
        assert(titles.slice(firstNull).every((t) => t === null), `NULLs last (${direction})`);
        const named = titles.slice(0, firstNull) as string[];
        const sorted = [...named].sort();
        assertEquals(named, direction === "asc" ? sorted : sorted.reverse());
      }

      // A filter.
      const filtered = await ask<"rows">(sql, {
        op: "rows",
        schema: "public",
        table: "notes",
        filter: { column: "title", value: "note 004" },
      });
      assertEquals(filtered.rows.map((r) => r.id), ["4"]);

      // A long value is cut in SQL for the list (one past the preview, so it reads as cut), and
      // read whole in the row view.
      await sql.unsafe("update notes set title = repeat('x', 300) where id = 3");
      const listed = await ask<"rows">(sql, {
        op: "rows",
        schema: "public",
        table: "notes",
        filter: { column: "id", value: "3" },
      });
      assertEquals(listed.rows[0].title?.length, 201);
      const one = await ask<"row">(sql, {
        op: "row",
        schema: "public",
        table: "notes",
        key: { id: "3" },
      });
      assertEquals(one.row?.title?.length, 300);

      // "As user": row-level security decides; the service role sees everything.
      const asUser = async (actor: DbActor) =>
        (await ask<"rows">(sql, { op: "rows", schema: "public", table: "notes", actor })).rows;
      const mine = await asUser({ kind: "user", id: A });
      assert(mine.length > 0 && mine.every((r) => r.owner === A));
      assertEquals(await asUser({ kind: "anon" }), []);
      assertEquals((await asUser({ kind: "service" })).length, 50);

      // A write previews (nothing changes), then runs that statement.
      const preview = await ask<"write">(sql, {
        op: "write",
        action: "update",
        schema: "public",
        table: "notes",
        key: { id: "4" },
        values: { title: "edited" },
        confirm: false,
      });
      assertEquals(preview.applied, false);
      assertEquals((await sql.unsafe("select title from notes where id = 4"))[0].title, "note 004");
      const run = await ask<"write">(sql, {
        op: "write",
        action: "update",
        schema: "public",
        table: "notes",
        key: { id: "4" },
        values: { title: "edited" },
        confirm: true,
      });
      assertEquals(run.statement, preview.statement);
      assertEquals(run.affected, 1);
      assertEquals((await sql.unsafe("select title from notes where id = 4"))[0].title, "edited");
      const inserted = await ask<"write">(sql, {
        op: "write",
        action: "insert",
        schema: "public",
        table: "notes",
        values: { owner: A, title: null },
        confirm: true,
      });
      assertEquals(inserted.affected, 1);
      assertEquals(
        (await sql.unsafe("select count(*)::int as n from notes where id = 121"))[0].n,
        1,
      );
      await ask<"write">(sql, {
        op: "write",
        action: "delete",
        schema: "public",
        table: "notes",
        key: { id: "121" },
        confirm: true,
      });
      const missing = await fails(sql, {
        op: "write",
        action: "delete",
        schema: "public",
        table: "notes",
        key: { id: "121" },
        confirm: true,
      });
      assertEquals(missing.code, "not_found");
      const badValue = await fails(sql, {
        op: "write",
        action: "update",
        schema: "public",
        table: "notes",
        key: { id: "5" },
        values: { owner: "not-a-uuid" },
        confirm: true,
      });
      assertEquals(badValue.code, "query_failed");
      assertStringIncludes(badValue.reason, "22P02");
      // An identifier that is not in the catalog never becomes SQL.
      const injected = await fails(sql, {
        op: "rows",
        schema: "public",
        table: 'notes"; drop table notes; --',
      });
      assertEquals(injected.code, "not_found");
      assertEquals((await sql.unsafe("select count(*)::int as n from notes"))[0].n, 120);

      // The server enforces READ ONLY and the statement timeout.
      const readOnly = await assertRejects(() =>
        inTransaction(
          sql,
          { readOnly: true, timeoutMs: 5000 },
          (tx) => Promise.resolve(tx.unsafe("insert into keyless values ('x')")),
        )
      );
      assertEquals(sqlState(readOnly), "25006");
      const slow = await assertRejects(() =>
        inTransaction(
          sql,
          { readOnly: true, timeoutMs: 200 },
          (tx) => Promise.resolve(tx.unsafe("select pg_sleep(3)")),
        )
      );
      assertEquals(sqlState(slow), "57014");

      const policies = await ask<"policies">(sql, { op: "policies" });
      assertEquals(policies.policies.map((p) => [p.table, p.name, p.command]), [
        ["notes", "read own notes", "SELECT"],
      ]);
      assert(policies.tables.every((t) => t.kind === "table"));
    } finally {
      await env.drop();
    }
  },
});

