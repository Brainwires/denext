// The two modules the plugin generates under `.denext/tanstack-start/`, each importing the app's
// router module: the server entry renders a request through TanStack Router's own SSR
// (`createRequestHandler` + `defaultRenderHandler` from `@tanstack/react-router/ssr/server`), the
// client entry hydrates the document with its `RouterClient`. Both are ordinary app modules, so
// `react` and `@tanstack/react-router` resolve through the app's import map (React → denext).

import { dirname, join, relative } from "@std/path";

/** A relative specifier from `fromDir` to `file`. */
function specifier(fromDir: string, file: string): string {
  const rel = relative(fromDir, file).replace(/\\/g, "/");
  return rel.startsWith(".") ? rel : `./${rel}`;
}

/** The router module's factory: `getRouter` (Start's name), else `createRouter`. */
const FACTORY = `const exported: Record<string, unknown> = { ...app };
const createRouter = exported.getRouter ?? exported.createRouter;
if (typeof createRouter !== "function") {
  throw new Error("@denext/tanstack-start: the router module exports no getRouter()");
}`;

/** The server entry: `render(request, manifest)` answers one page request. */
export function serverEntrySource(dir: string, routerFile: string): string {
  return `// Generated by @denext/tanstack-start — do not edit.
import { createRequestHandler, defaultRenderHandler } from "@tanstack/react-router/ssr/server";
import * as app from ${JSON.stringify(specifier(dir, routerFile))};

${FACTORY}

/** Render \`request\` through TanStack Router's SSR, the client entry in its manifest. */
export function render(request: Request, manifest: unknown): Promise<Response> {
  return createRequestHandler({
    request,
    createRouter: createRouter as never,
    getRouterManifest: () => manifest as never,
  })(defaultRenderHandler);
}
`;
}

/** The client boot module: hydrate the whole document with the router's dehydrated state. */
export function clientBootSource(dir: string, routerFile: string): string {
  return `// Generated by @denext/tanstack-start — do not edit.
import { createElement } from "react";
import { hydrateRoot } from "react-dom/client";
import { RouterClient } from "@tanstack/react-router/ssr/client";
import * as app from ${JSON.stringify(specifier(dir, routerFile))};

${FACTORY}

hydrateRoot(document, createElement(RouterClient, { router: (createRouter as () => never)() }));
`;
}

/** The bundled client entry: the boot module, by absolute path. */
export function clientEntrySource(bootFile: string): string {
  return `import ${JSON.stringify(bootFile.replace(/\\/g, "/"))};\n`;
}

/** Write a file when its content changed. */
export async function writeIfChanged(path: string, content: string): Promise<void> {
  const current = await Deno.readTextFile(path).catch(() => null);
  if (current === content) return;
  await Deno.mkdir(dirname(path), { recursive: true });
  await Deno.writeTextFile(path, content);
}

/** Where the generated modules live. */
export function entryPaths(outDir: string): { server: string; boot: string } {
  return { server: join(outDir, "server-entry.ts"), boot: join(outDir, "client-boot.ts") };
}
