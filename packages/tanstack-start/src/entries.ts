// The two modules the plugin generates under `.denext/tanstack-start/`. The server entry is
// TanStack Start's own request handler (`createStartHandler(defaultStreamHandler)` from
// `@tanstack/react-start/server`, what Start's default server entry exports) — or the app's
// `src/server.ts` when it has one; the client entry hydrates the document with Start's
// `StartClient` — or runs the app's `src/client.tsx`. Both are ordinary app modules, so `react`
// and the `@tanstack/*` packages resolve through the app's import map (React → denext).

import { dirname, join } from "@std/path";

/** A path as a module specifier (forward slashes). */
const spec = (path: string) => JSON.stringify(path.replace(/\\/g, "/"));

/**
 * The server entry: `fetch(request)` answers a page, server-function or server-route request.
 *
 * @param customServer The app's `src/server.ts` (its default export has `fetch`), or `null`.
 */
export function serverEntrySource(customServer: string | null): string {
  if (customServer) {
    return `// Generated by @denext/tanstack-start — do not edit.
import entry from ${spec(customServer)};

/** The app's own server entry (\`src/server.ts\`). */
export function fetch(request: Request): Promise<Response> {
  return Promise.resolve(entry.fetch(request));
}
`;
  }
  return `// Generated by @denext/tanstack-start — do not edit.
import { createStartHandler, defaultStreamHandler } from "@tanstack/react-start/server";

/** TanStack Start's request handler: server functions, server routes, streamed pages. */
export const fetch: (request: Request) => Promise<Response> = createStartHandler(
  defaultStreamHandler,
) as never;
`;
}

/**
 * The client boot module: hydrate the whole document with Start's `StartClient`.
 *
 * @param customClient The app's `src/client.tsx`, or `null`.
 */
export function clientBootSource(customClient: string | null): string {
  const header = "// Generated by @denext/tanstack-start — do not edit.\n";
  if (customClient) return `${header}import ${spec(customClient)};\n`;
  return `${header}import { createElement, startTransition } from "react";
import { hydrateRoot } from "react-dom/client";
import { StartClient } from "@tanstack/react-start/client";

startTransition(() => {
  hydrateRoot(document, createElement(StartClient));
});
`;
}

/** The bundled client entry: the boot module, by absolute path. */
export function clientEntrySource(bootFile: string): string {
  return `import ${spec(bootFile)};\n`;
}

/** Write a file when its content changed. */
export async function writeIfChanged(path: string, content: string): Promise<void> {
  const current = await Deno.readTextFile(path).catch(() => null);
  if (current === content) return;
  await Deno.mkdir(dirname(path), { recursive: true });
  await Deno.writeTextFile(path, content);
}

/** Where the generated modules live. */
export function entryPaths(outDir: string): { server: string; boot: string } {
  return { server: join(outDir, "server-entry.ts"), boot: join(outDir, "client-boot.ts") };
}
