/**
 * Helpers every client emitter shares.
 *
 * @module
 */

import type { ModelOperation, NamedType, TypeRef } from "./model.ts";

/** A double-quoted string literal (JSON's escapes are valid in every target language). */
export function quote(s: string): string {
  return JSON.stringify(s);
}

/** The types sorted by name (a stable, diff-friendly order). */
export function sortedTypes(types: readonly NamedType[]): NamedType[] {
  return [...types].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

/** The named types a type reference mentions. */
function namesIn(ref: TypeRef): string[] {
  switch (ref.kind) {
    case "named":
      return [ref.name];
    case "array":
      return namesIn(ref.items);
    case "map":
      return namesIn(ref.values);
    case "nullable":
      return namesIn(ref.inner);
    default:
      return [];
  }
}

/** Aliases ordered so each comes after the aliases it refers to (a cycle keeps input order). */
export function orderAliases(aliases: NamedType[]): NamedType[] {
  const byName = new Map(aliases.map((a) => [a.name, a]));
  const out: NamedType[] = [];
  const state = new Map<string, "visiting" | "done">();
  const visit = (a: NamedType) => {
    if (state.get(a.name)) return;
    state.set(a.name, "visiting");
    if (a.kind === "alias") {
      for (const dep of namesIn(a.target)) {
        const next = byName.get(dep);
        if (next) visit(next);
      }
    }
    state.set(a.name, "done");
    out.push(a);
  };
  for (const a of aliases) visit(a);
  return out;
}

/** The header line every generated file starts with. */
export function banner(title: string, version: string, verb: string, lang: string): string {
  return `${
    [title, version].filter(Boolean).join(" ")
  } — a typed client generated by \`denext ${verb} client --lang ${lang}\`. Do not edit.`;
}

/** `text` as line comments (`//`, `///`, `#`), each line prefixed by `indent`; "" for none. */
export function lineComment(text: string | undefined, indent: string, marker: string): string {
  if (!text) return "";
  return text.split("\n").map((l) => `${indent}${marker} ${l}`.trimEnd()).join("\n") + "\n";
}

/** An operation's doc lines: its summary, `METHOD /path`, and the error codes it may raise. */
export function operationDoc(
  op: ModelOperation,
  raises: (codes: string) => string,
): string[] {
  const codes = Object.keys(op.errors);
  return [
    ...(op.summary ? [op.summary] : []),
    `\`${op.method} ${op.path}\``,
    ...(codes.length ? [raises(codes.join(", "))] : []),
  ];
}

/** `literal` (a quoted path template) with each `{param}` replaced by `insert(param)`. */
export function fillPath(
  literal: string,
  op: ModelOperation,
  insert: (name: string) => string,
): string {
  let out = literal;
  for (const p of op.pathParams) out = out.replace(`{${p.name}}`, insert(p.name));
  return out;
}

/**
 * A type-reference printer from a table of scalar spellings and the composite forms — every
 * emitter's `TypeRef` → type-name function.
 */
export function typePrinter(
  scalars: Record<"string" | "integer" | "number" | "boolean" | "any", string>,
  forms: {
    array: (items: string) => string;
    map: (values: string) => string;
    named: (name: string) => string;
    nullable: (inner: TypeRef, print: (ref: TypeRef) => string) => string;
  },
): (ref: TypeRef) => string {
  const print = (ref: TypeRef): string => {
    if (ref.kind === "array") return forms.array(print(ref.items));
    if (ref.kind === "map") return forms.map(print(ref.values));
    if (ref.kind === "named") return forms.named(ref.name);
    if (ref.kind === "nullable") return forms.nullable(ref.inner, print);
    return scalars[ref.kind];
  };
  return print;
}

/** The query parameters of `op`, each rendered by `item`, comma-separated. */
export function queryItems(
  op: ModelOperation,
  item: (wire: string, param: ModelOperation["queryParams"][number]) => string,
): string {
  return op.queryParams.map((q) => item(q.name, q)).join(", ");
}
