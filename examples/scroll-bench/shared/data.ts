/**
 * Deterministic, seeded, LAZY bench data. `makeItems(kind, n, seed)` returns a {@link BenchList}:
 * a snapshot whose item at any position is generated on demand from `(seed, index)` alone, so
 * 10M rows cost nothing until they are drawn, and the web app and the React Native app draw
 * byte-identical content for the same `(kind, n, seed)`.
 *
 * Plain TypeScript: no React, no platform imports (Deno, the browser and Metro all load it).
 */

import { FIXED, HEADER } from "./theme.ts";

export type Kind = "fixed" | "chat" | "images" | "sections";

/** A `fixed` row, and every non-header row of `sections`. */
export interface RowItem {
  type: "row";
  id: string;
  title: string;
  subtitle: string;
  time: string;
  initials: string;
  color: number;
}

/** A `sections` header. */
export interface HeaderItem {
  type: "header";
  id: string;
  title: string;
  count: number;
}

/** One run of inline text: plain, bold, a link or inline code. */
export interface Span {
  text: string;
  bold?: boolean;
  href?: string;
  code?: boolean;
}

export type ChatBlock =
  | { type: "p"; spans: Span[] }
  | { type: "code"; lang: string; lines: string[] };

export interface ChatItem {
  type: "chat";
  id: string;
  role: "user" | "assistant";
  blocks: ChatBlock[];
}

export interface ImageItem {
  type: "image";
  id: string;
  /** Index into {@link IMAGE_ASSETS}. */
  image: number;
  caption: string;
}

export type Item = RowItem | HeaderItem | ChatItem | ImageItem;

