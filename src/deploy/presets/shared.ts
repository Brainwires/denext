// What the deploy presets share: the generated-file markers, the app's name, and the facts of the
// manifest every preset reports on (secrets, schedules, routes that need a server).

import { basename } from "@std/path";
import type { DeployManifest, DeployRoute } from "../manifest.ts";

/**
 * The line a preset's project file opens with (after the comment leader): its presence lets the
 * next `prepare` replace the file, and deleting it keeps your edits.
 *
 * @param preset The preset's name.
 * @returns The marker text.
 */
export function marker(preset: string): string {
  return `Generated by \`denext deploy\` (${preset})`;
}

/**
 * A file header carrying the marker, in a comment syntax.
 *
 * @param preset The preset's name.
 * @param leader The comment leader (`#`, `//`).
 * @returns The two header lines.
 */
export function header(preset: string, leader: string): string {
  return `${leader} ${marker(preset)}. Regenerated by every \`denext deploy prepare\`;\n` +
    `${leader} delete this line to keep your edits.`;
}

/**
 * An app name a host accepts (lowercase letters, digits and dashes), from an explicit one or the
 * project directory's name.
 *
 * @param explicit The name the options gave.
 * @param projectDir The project root.
 * @returns The name.
 */
export function appName(explicit: string | undefined, projectDir: string): string {
  const raw = explicit ?? basename(projectDir);
  const name = raw.toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "");
  return name || "denext-app";
}

/**
 * The variables the app needs set (a secret the stack needs, or an asserted read), public ones
 * left out (they are not secret).
 *
 * @param manifest The deploy manifest.
 * @returns Their names, sorted.
 */
export function requiredSecrets(manifest: DeployManifest): string[] {
  return manifest.env.filter((v) => v.required && !v.public).map((v) => v.name);
}

/**
 * The routes a static host cannot serve: everything but `"static"`.
 *
 * @param manifest The deploy manifest.
 * @returns The routes, in manifest order.
 */
export function serverRoutes(manifest: DeployManifest): DeployRoute[] {
  return manifest.routes.filter((r) => r.kind !== "static");
}

/**
 * One line describing a route for a report: `/api/x  route-handler (app/api/x/route.ts) — why`.
 *
 * @param route The route.
 * @returns The line.
 */
export function describeRoute(route: DeployRoute): string {
  return `${route.path}  ${route.kind} (${route.source})${
    route.reason ? ` — ${route.reason}` : ""
  }`;
}
