// The `jobs/migrate.ts` an older `denext generate migration` wrote applied each `migrations/*.sql`
// file whole on SQLite. Migration files now carry a `-- migrate:down` section (and may have a
// `<name>.down.sql` companion, which that runner reads as a migration of its own), so the old
// runner would apply a migration and at once undo it — a `DROP TABLE` right after the
// `CREATE TABLE`. `denext generate migration` replaces such a runner; until then, the job loader
// wraps it so it refuses to run while any file holds a down script.

import { join } from "@std/path";
import { isJob, type Job } from "./jobs.ts";
import { splitMigration } from "./migration-files.ts";
import { isPostgresUrl } from "./postgres.ts";

/** The first line every generated runner starts with. */
const SENTINEL = "// Generated by `denext generate migration`";

/**
 * Whether `source` is the runner an older `denext generate migration` wrote (a generated one
 * without `migrateSqlite`). A hand-written runner is not recognised and is left alone.
 *
 * @param source The job's source.
 * @returns True for the old generated runner.
 */
export function isLegacyMigrateJob(source: string): boolean {
  return source.includes(SENTINEL) && !source.includes("migrateSqlite");
}

/**
 * The files in `dir` the old runner would mishandle: `.down.sql` companions, and files with a
 * `-- migrate:down` section.
 *
 * @param dir The migrations directory.
 * @returns Their names, sorted.
 */
export async function filesWithDownScripts(dir: string): Promise<string[]> {
  const found: string[] = [];
  try {
    for await (const entry of Deno.readDir(dir)) {
      if (!entry.isFile || !entry.name.endsWith(".sql")) continue;
      if (entry.name.endsWith(".down.sql")) {
        found.push(entry.name);
        continue;
      }
      const text = await Deno.readTextFile(join(dir, entry.name));
      if (splitMigration(text).down !== undefined) found.push(entry.name);
    }
  } catch (error) {
    if (!(error instanceof Deno.errors.NotFound)) throw error;
  }
  return found.sort();
}

/** Whether the old runner would take its Postgres path (`DATABASE_URL` is a postgres:// URL). */
function onPostgres(): boolean {
  try {
    return isPostgresUrl(Deno.env.get("DATABASE_URL"));
  } catch {
    return false;
  }
}

/**
 * Guard an old generated `jobs/migrate.ts`: the job refuses to run while a migration holds a
 * down script, naming the files and the fix. Any other job is returned as is.
 *
 * @param job The loaded job.
 * @param source Its module's source.
 * @param migrationsDir The `migrations/` directory beside `jobs/`.
 * @returns The job to register.
 */
export function guardLegacyMigrateJob(job: Job, source: string, migrationsDir: string): Job {
  if (!isLegacyMigrateJob(source) || !isJob(job)) return job;
  return {
    ...job,
    handler: async (ctx) => {
      // On Postgres the old runner calls migratePostgres, which runs only the up section.
      const unsafe = onPostgres() ? [] : await filesWithDownScripts(migrationsDir);
      if (unsafe.length) {
        throw new Error(
          `jobs/migrate.ts was generated by an older denext and runs each file whole, so it ` +
            `would also run the down scripts in ${unsafe.join(", ")} (undoing what it applies). ` +
            "Refusing. Replace the runner: `denext generate migration <name>` rewrites it " +
            "(or apply the migrations with `denext migration up`).",
        );
      }
      return await job.handler(ctx);
    },
  };
}
