/// The native side of \`isScreenReaderEnabled()\` / \`onScreenReaderChange()\` from
/// \`denext/mobile\`, reached from the web app as \`window.Capacitor.Plugins.DenextAccessibility\`.
/// \`DenextBridgeViewController\` registers it.
///
/// - \`isScreenReaderEnabled()\`: resolves \`{ value }\`, whether VoiceOver is running.
/// - \`screenReaderChanged\` event: \`{ value }\`, sent when VoiceOver is turned on or off.
