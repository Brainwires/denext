// The comment heading every widget / Live Activity file denext writes, shared by
// widget-native-templates.ts and the templates' readable source (native-templates/widget.ts).

/**
 * The header comment of a widget / Live Activity file.
 *
 * @param verb The `denext mobile add` verb that writes the file.
 * @param editable Whether the app may edit the file (denext then keeps its version).
 * @returns The comment lines.
 */
export const HEADER = (verb: string, editable: boolean): string =>
  `// Generated by denext mobile add ${verb} (denext app extensions). Safe to commit${
    editable ? " and to\n// edit (denext then keeps your version)" : ""
  }; re-run it after upgrading denext (then ship a new binary).\n// See https://denext.dev/docs/desktop.\n`;
