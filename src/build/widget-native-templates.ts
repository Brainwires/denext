/** `OrderProgress` → `order_progress` (Android resource names). */
export function snakeName(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/([A-Z])([A-Z][a-z])/g, "$1_$2")
    .toLowerCase();
}

