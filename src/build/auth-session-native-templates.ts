// The native halves of `openAuthSession()` (denext/mobile), embedded as text so they ship
// inside the JSR package: `denext mobile add auth-session` writes them into a Capacitor project.
// iOS: `DenextAuthSessionPlugin.swift` for `ios/App/App/` (an ASWebAuthenticationSession sheet),
// plus the bridge view controller that registers it when the project has no over-the-air UI
// (with OTA, the OTA bridge view controller registers both; see mobile-native-install.ts).
// Android: `DenextAuthSessionPlugin.java` in package `dev.denext.authsession` (a Custom Tab, and
// the callback taken from the app's own scheme intent filter).
//
// Edit these as source in native-templates/auth-session.ts:
// they are compiled only in an app (build-checked with xcodebuild and
// Gradle against Capacitor 8). Every `\`` and `\${` there is an escaped template-literal
// character, not part of the Swift/Java.
//
// Every file is written through `renderAuthSessionTemplate`, which puts a marker line on top:
// the template generation and the SHA-256 of the rest of the file. A file whose marker still
// matches its body is an unedited denext template and is upgraded in place by a later run; an
// edited one is kept. Bump AUTH_SESSION_TEMPLATE_VERSION when the templates change.
//
// The template texts ship packed: native-templates/auth-session.ts (the readable source, not published)
// is packed with the others into native-templates.packed.ts by `deno task gen:native-templates`.

import { markedTemplateIntact, renderMarkedTemplate } from "./native-template-marker.ts";
import { withFrameGuard } from "./bridge-frame-guard-native-template.ts";
import { withMemoryWarning } from "./bridge-memory-warning-native-template.ts";
import { withExportRouter } from "./bridge-export-router-native-template.ts";
import { NATIVE_TEMPLATES } from "./native-templates.packed.ts";

/**
 * The generation of the templates, stamped into every file the installer writes.
 * Generation 2 (denext 2.11): the auth-session-only `DenextBridgeViewController` drops native
 * bridge calls from frames other than the main one (see bridge-frame-guard-native-template.ts);
 * the bump makes 2.10.0 (generation 1) keep such a bridge instead of rewriting it unguarded.
 * Generation 3: the bridge serves an exported multi-page app's routes (`DenextExportRouter`, see
 * bridge-export-router-native-template.ts); the bump keeps an older denext from rewriting it away.
 * Generation 4: the router refuses a path that leaves the UI directory (a decoded `/../secret`);
 * the bump keeps an older denext from rewriting that check away.
 * Generation 5: the bridge forwards the OS's low-memory warning to the page
 * (`DenextMemoryWarning`, see bridge-memory-warning-native-template.ts: React Native mode's
 * `AppState` `memoryWarning`); the bump keeps an older denext from rewriting it away.
 */
export const AUTH_SESSION_TEMPLATE_VERSION = 5;

/**
 * A template as the installer writes it: a first line
 * `// denext-auth-session-template: <AUTH_SESSION_TEMPLATE_VERSION> sha256=<hex>` (the SHA-256 of
 * everything after that line), then the template.
 *
 * @param template The template text.
 * @returns The file content.
 */
export function renderAuthSessionTemplate(template: string): Promise<string> {
  return renderMarkedTemplate("auth-session", AUTH_SESSION_TEMPLATE_VERSION, template);
}

/**
 * Whether `text` is an unedited auth-session template: its marker line matches its body.
 *
 * @param text A file's content.
 * @returns `true` when the file carries an intact marker.
 */
export async function isPristineAuthSessionTemplate(text: string): Promise<boolean> {
  return await markedTemplateIntact("auth-session", text) === true;
}

/**
 * `DenextBridgeViewController.swift` for a project without the over-the-air UI: it only
 * registers `DenextAuthSessionPlugin`. With OTA installed, the OTA bridge view controller
 * (which also registers this plugin) is written instead.
 */
export const AUTH_SESSION_BRIDGE_VIEW_CONTROLLER: string = withExportRouter(
  withFrameGuard(withMemoryWarning(
    `// Generated by \`denext mobile add auth-session\` (denext native plugins). Safe to commit;
// re-run it after upgrading denext (then ship a new binary). \`denext mobile add-ota\` replaces
// this file with one that also serves the over-the-air UI. See https://denext.dev/docs/desktop.

@preconcurrency import Capacitor
import UIKit

/// A \`CAPBridgeViewController\` that registers denext's native plugins (here
/// \`DenextAuthSession\`, behind \`openAuthSession()\` in \`denext/mobile\`) before the first page.
///
/// Use it where the app would use \`CAPBridgeViewController\`: \`Main.storyboard\`'s view
/// controller class and \`SceneDelegate\`'s root view controller (the installer sets both when
/// they still name \`CAPBridgeViewController\`). An app with its own bridge subclass changes that
/// subclass's superclass to \`DenextBridgeViewController\` and calls \`super\` from any
/// \`capacitorDidLoad()\` override.
///
/// \`CAPBridgeViewController.loadView()\` creates the bridge and then calls \`capacitorDidLoad()\`;
/// the page itself loads later, from \`viewDidLoad()\`, so the plugin exists before any script.
class DenextBridgeViewController: CAPBridgeViewController {
    override func capacitorDidLoad() {
        super.capacitorDidLoad()
        bridge?.registerPluginInstance(DenextAuthSessionPlugin())
    }
}
`,
  )),
);

