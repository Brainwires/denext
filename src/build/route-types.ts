// Typed routes (2.0 Pillar V): turn the scanned route manifest into a TypeScript type
// module so navigation is type-checked against the routes that actually exist. Emitted to
// `<outDir>/routes.ts` on every `denext build` / `denext dev`; an app imports the types:
//
//   import type { Routes, ParamsOf } from "./.denext/routes.ts";
//   const go = (href: Routes) => router.push(href);           // only real paths compile
//   type BlogParams = ParamsOf<"/blog/[slug]">;               // { slug: string }
//
// Dynamic segments become `${string}` template literals; catch-all spans the tail; an
// optional catch-all yields both the with- and without-tail variants. All params are
// strings (denext joins catch-all segments into one string, matching its RouteParams).

import type { RouteManifest } from "../router/manifest.ts";
import type { Segment } from "../router/segments.ts";

/** TS type expression(s) for one route's path (an optional catch-all yields two). */
function pathTypes(pattern: Segment[]): string[] {
  const optIdx = pattern.findIndex((s) => s.kind === "optionalCatchAll");
  if (optIdx >= 0) {
    // `[[...x]]` matches both the prefix path and prefix + one-or-more segments.
    const before = pattern.slice(0, optIdx);
    const withTail: Segment[] = [
      ...before,
      { kind: "catchAll", value: pattern[optIdx].value },
    ];
    return [...pathTypes(before), ...pathTypes(withTail)];
  }
  let hasVar = false;
  let s = "";
  for (const seg of pattern) {
    if (seg.kind === "static") s += "/" + seg.value;
    else {
      s += "/${string}"; // dynamic or catch-all → any segment text
      hasVar = true;
    }
  }
  if (s === "") s = "/";
  // A fully-static route is a string literal; a variable route is a template literal.
  return [hasVar ? "`" + s + "`" : JSON.stringify(s)];
}

/** Params object type for one route pattern (all params are strings in denext). */
function paramsType(pattern: Segment[]): string {
  const entries = pattern
    .filter((s) => s.kind !== "static")
    .map((s) => `${JSON.stringify(s.value)}: string`);
  return entries.length ? `{ ${entries.join("; ")} }` : "Record<never, never>";
}

function unionOf(types: string[]): string {
  const uniq = [...new Set(types)].sort();
  return uniq.length ? uniq.join(" | ") : "never";
}

/** Generate the `<outDir>/routes.ts` typed-routes module from a scanned manifest. */
export function generateRouteTypes(manifest: RouteManifest): string {
  const pages = manifest.pages ?? [];
  const api = manifest.api ?? [];

  const routeUnion = unionOf(pages.flatMap((p) => pathTypes(p.pattern)));
  const apiUnion = unionOf(api.flatMap((a) => pathTypes(a.pattern)));

  // One RouteParams entry per distinct page route pattern, stable-sorted.
  const seen = new Set<string>();
  const paramLines: string[] = [];
  for (const p of [...pages].sort((a, b) => a.routePath.localeCompare(b.routePath))) {
    if (seen.has(p.routePath)) continue;
    seen.add(p.routePath);
    paramLines.push(`  ${JSON.stringify(p.routePath)}: ${paramsType(p.pattern)};`);
  }

  // Wire the routes into denext so Link / router.push enforce them — but only when the
  // app actually has routes (a `routes: never` augmentation would make every href fail).
  const augmentation = routeUnion === "never" ? "" : `
// Enforce these routes on \`Link\` / \`router.push\` / \`router.replace\`. Import this file
// anywhere in your app (e.g. \`import "./.denext/routes.ts";\`) for it to take effect.
declare module "denext" {
  interface RegisteredRoutes {
    routes: Routes;
  }
}
`;

  return `// AUTO-GENERATED by denext — DO NOT EDIT.
// Regenerated on \`denext build\` / \`denext dev\`. Import these types to make navigation
// type-safe:
//
//   import type { Routes, ParamsOf } from "./.denext/routes.ts";
//
/** Every valid page route in this app (dynamic segments as \`\${string}\`). */
export type Routes = ${routeUnion};

/** Every API route in this app. */
export type ApiRoutes = ${apiUnion};

/** The params object for each page route pattern (all values are strings). */
export interface RouteParams {
${paramLines.join("\n") || "  // (no routes)"}
}

/** The params object type for a given route pattern, e.g. \`ParamsOf<"/blog/[slug]">\`. */
export type ParamsOf<R extends keyof RouteParams> = RouteParams[R];
${augmentation}`;
}
