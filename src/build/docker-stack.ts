// The self-hosted stack half of `denext generate docker`: the compose file with Postgres, an
// S3 store (MinIO) and its bucket bootstrap, a one-shot migrations service, the `.env.example`
// that lists every secret those services and the app read, and the development overlay
// (`compose.dev.yml`). `docker-template.ts` renders the Dockerfile and the plain compose file
// and hands the stack layout to this module; `docker-detect.ts` decides which services a
// project needs.
//
// Every secret the stack knows about is ONE entry in {@linkcode STACK_ENV}: the `.env.example`
// line, its "how to generate it" comment, and (for the app's own secrets) the pass-through into
// the app and migrations containers all come from that entry, so a new secret is a one-line
// change. Nothing here writes a real secret: `.env.example` carries placeholders and the
// compose file reads `.env`, failing fast (`${NAME:?…}`) when a required one is missing.
//
// Build-time only; never imported by a shipped bundle.

/**
 * The header comment every generated Docker file carries. Its presence is what makes a
 * regeneration safe: a file without it was written (or edited) by a human and is left alone.
 */
export const DOCKER_SENTINEL = "# Generated by `denext generate docker`";

/** The services and secrets the stack is rendered with. */
export interface StackOptions {
  /** A Postgres service, its named volume, and `DATABASE_URL` wired into the app. */
  readonly postgres?: boolean;
  /** Use the pgvector image (`pgvector/pgvector:pg17`) for the Postgres service. */
  readonly pgvector?: boolean;
  /** An S3 store (MinIO), a one-shot bucket bootstrap, and the `AWS_*` / `S3_*` app env. */
  readonly storage?: boolean;
  /** A one-shot migrations service (`denext job migrate`) the app waits for. */
  readonly migrate?: boolean;
  /** Publish Postgres on `127.0.0.1:5432` (off by default: the app reaches it on the network). */
  readonly exposeDb?: boolean;
  /** Also write `compose.dev.yml`: `denext dev` on a bind mount, database and store published. */
  readonly dev?: boolean;
  /** The app signs in with `denextAuth` (adds `AUTH_SECRET`). */
  readonly auth?: boolean;
  /** The app uses `@denext/backend` (adds the backend's JWT and vault keys). */
  readonly backend?: boolean;
  /** `@denext/backend` storage is configured (adds `DENEXT_STORAGE_SECRET`). */
  readonly backendStorage?: boolean;
  /** The S3 bucket the bootstrap creates (default `denext`). */
  readonly bucket?: string;
  /** The `deno run -A` arguments that run denext's CLI (default: `jsr:@denext/denext/cli`). */
  readonly cli?: readonly string[];
  /** The command the migrations service runs (default: the project's `migrate` task). */
  readonly migrateCommand?: readonly string[];
}

/** One variable `.env.example` lists. */
interface StackEnvVar {
  /** The variable's name. */
  readonly name: string;
  /** What it is for (the comment above it). */
  readonly about: string;
  /** How to generate a value (shown as `# Generate: …`), for a secret. */
  readonly generate?: string;
  /** The default written into `.env.example` (a required secret is written empty). */
  readonly example?: string;
  /** Required: compose refuses to start without it (`${NAME:?…}`). */
  readonly required: boolean;
  /** Handed to the app and migrations containers under its own name. */
  readonly app: boolean;
  /** Whether these options need it. */
  readonly when: (options: StackOptions) => boolean;
}

