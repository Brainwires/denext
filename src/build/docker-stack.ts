/** The variables these options need, in {@linkcode STACK_ENV} order. */
export function stackEnv(options: StackOptions): StackEnvVar[] {
  return STACK_ENV.filter((v) => v.when(options));
}

/**
 * Whether the app must run on denext's Deno toolchain: `@denext/backend`'s Postgres client
 * (`Deno.SQL`) is part of it, and the least-privilege `start` task cannot re-exec onto it.
 */
export function needsToolchain(options: StackOptions): boolean {
  return options.postgres === true || options.backend === true;
}

/** Whether these options render the stack layout (any service beyond the app). */
export function isStack(options: StackOptions): boolean {
  return options.postgres === true || options.storage === true || options.migrate === true;
}

/** A compose interpolation, `${…}`, without fighting the template literal. */
function ref(inner: string): string {
  return "${" + inner + "}";
}

/** The interpolation for a {@linkcode STACK_ENV} variable: required ones fail fast. */
function envRef(name: string): string {
  const v = STACK_ENV.find((e) => e.name === name);
  if (v?.required) return ref(`${name}:?${MISSING}`);
  return ref(`${name}:-${v?.example ?? ""}`);
}

/** Postgres published on loopback only (`DB_PORT` in `.env` moves it off 5432). */
const DB_PORT = `127.0.0.1:${ref("DB_PORT:-5432")}:5432`;

/** Postgres images: plain 17, or pgvector's build of 17. */
const POSTGRES_IMAGE = "postgres:17-alpine";
const PGVECTOR_IMAGE = "pgvector/pgvector:pg17";

/**
 * The MinIO image. MinIO no longer publishes pullable images (`minio/minio`, `minio/mc` and
 * `quay.io/minio/*` refuse anonymous pulls), so this is Bitnami's legacy build of the same server,
 * pinned by digest; it ships `mc` too, which the bucket bootstrap uses. `MINIO_IMAGE` in `.env`
 * swaps it for any MinIO-compatible image with `mc` on its PATH.
 */
const MINIO_IMAGE =
  "bitnamilegacy/minio:2025.7.23-debian-12-r5@sha256:6dabb4a2088c9a79908de3bc05f4586c23ad2182c8908e7e3acbf61c1467fb20";

/** The app's own image name, shared by the app and migrations services (built once). */
const APP_IMAGE = ref("APP_IMAGE:-denext-app");

/** The `DATABASE_URL` the app and migrations containers get. */
function databaseUrl(): string {
  return `postgres://${envRef("POSTGRES_USER")}:${envRef("POSTGRES_PASSWORD")}@db:5432/${
    envRef("POSTGRES_DB")
  }`;
}

/** The `environment:` lines (6-space indented) the app and migrations containers share. */
function appEnvLines(options: StackOptions): string[] {
  const lines: string[] = [];
  if (options.postgres) lines.push(`DATABASE_URL: ${databaseUrl()}`);
  if (options.storage) {
    const bucket = ref(`S3_BUCKET:-${options.bucket ?? "denext"}`);
    lines.push(
      `AWS_ACCESS_KEY_ID: ${envRef("MINIO_ROOT_USER")}`,
      `AWS_SECRET_ACCESS_KEY: ${envRef("MINIO_ROOT_PASSWORD")}`,
      `AWS_REGION: us-east-1`,
      `AWS_ENDPOINT_URL: ${envRef("S3_ENDPOINT")}`,
      `S3_ENDPOINT: ${envRef("S3_ENDPOINT")}`,
      `S3_REGION: us-east-1`,
      `S3_BUCKET: ${bucket}`,
    );
  }
  for (const v of stackEnv(options)) {
    if (v.app) lines.push(`${v.name}: ${envRef(v.name)}`);
  }
  return lines;
}

/** Indent every line of `lines` by `n` spaces. */
function indent(lines: readonly string[], n: number): string {
  const pad = " ".repeat(n);
  return lines.map((l) => pad + l).join("\n");
}

/** The app's `depends_on:` block, in start order. */
function appDependsOn(options: StackOptions): string[] {
  const deps: string[] = [];
  if (options.postgres) deps.push("db:", "  condition: service_healthy");
  if (options.storage) deps.push("minio-init:", "  condition: service_completed_successfully");
  if (options.migrate) deps.push("migrate:", "  condition: service_completed_successfully");
  return deps;
}

/** The app service's liveness probe (the same one the Dockerfile bakes in). */
function appHealthcheck(port: number, static_: boolean): string {
  const path = static_ ? "/" : "/_denext/health";
  const probe =
    `fetch('http://127.0.0.1:${port}${path}').then((r)=>Deno.exit(r.ok?0:1)).catch(()=>Deno.exit(1))`;
  return `    healthcheck:
      test: ["CMD", "deno", "eval", "${probe}"]
      interval: 30s
      timeout: 5s
      retries: 3
      start_period: 20s`;
}

/** The `web` service. */
function webService(options: StackOptions, port: number, static_: boolean): string {
  const deps = appDependsOn(options);
  return `  web:
    build: .
    image: ${APP_IMAGE}
    restart: unless-stopped
    ports:
      - "${port}:${port}"
    # Anything else the app reads at runtime: put it in .env (optional file).
    env_file:
      - path: .env
        required: false
    environment:
${indent(["NODE_ENV: production", ...appEnvLines(options)], 6)}
${appHealthcheck(port, static_)}${deps.length ? `\n    depends_on:\n${indent(deps, 6)}` : ""}`;
}

/** The one-shot migrations service: the app's image, `denext job migrate`, then exit. */
function migrateService(options: StackOptions): string {
  const command = JSON.stringify(options.migrateCommand ?? ["deno", "task", "migrate"])
    .replaceAll('","', '", "');
  const env = appEnvLines(options);
  const lines = [
    `  # Applies pending migrations/*.sql (jobs/migrate.ts) once, then exits; the app waits for it.`,
    `  migrate:`,
    `    image: ${APP_IMAGE}`,
    `    pull_policy: never`,
    `    command: ${command}`,
    `    restart: "no"`,
    `    env_file:`,
    `      - path: .env`,
    `        required: false`,
    ...(env.length ? [`    environment:`, indent(env, 6)] : []),
    ...(options.postgres
      ? [`    depends_on:`, `      db:`, `        condition: service_healthy`]
      : []),
  ];
  return lines.join("\n");
}

/** The Postgres service. No host port unless `exposeDb` (the app reaches it as `db:5432`). */
function dbService(options: StackOptions): string {
  const ports = options.exposeDb ? `\n    ports:\n      - "${DB_PORT}"` : "";
  return `  db:
    image: ${options.pgvector ? PGVECTOR_IMAGE : POSTGRES_IMAGE}
    restart: unless-stopped
    environment:
      POSTGRES_USER: ${envRef("POSTGRES_USER")}
      POSTGRES_PASSWORD: ${envRef("POSTGRES_PASSWORD")}
      POSTGRES_DB: ${envRef("POSTGRES_DB")}
    volumes:
      - db-data:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U \\"$$POSTGRES_USER\\" -d \\"$$POSTGRES_DB\\""]
      interval: 5s
      timeout: 5s
      retries: 20
      start_period: 10s${ports}`;
}

/** The MinIO service and the one-shot that creates the bucket. */
function storageServices(options: StackOptions): string {
  const image = ref(`MINIO_IMAGE:-${MINIO_IMAGE}`);
  const bucket = ref(`S3_BUCKET:-${options.bucket ?? "denext"}`);
  return `  # MinIO publishes no pullable images any more; this is Bitnami's legacy build of the same
  # server (with \`mc\`), pinned by digest. MINIO_IMAGE in .env swaps in any MinIO-compatible image.
  minio:
    image: ${image}
    restart: unless-stopped
    environment:
      MINIO_ROOT_USER: ${envRef("MINIO_ROOT_USER")}
      MINIO_ROOT_PASSWORD: ${envRef("MINIO_ROOT_PASSWORD")}
    volumes:
      - storage-data:/bitnami/minio/data
    healthcheck:
      test: ["CMD", "curl", "-fsS", "http://127.0.0.1:9000/minio/health/live"]
      interval: 5s
      timeout: 5s
      retries: 20
      start_period: 10s

  # Creates the bucket once (idempotent), then exits; the app waits for it.
  minio-init:
    image: ${image}
    restart: "no"
    depends_on:
      minio:
        condition: service_healthy
    environment:
      MINIO_ROOT_USER: ${envRef("MINIO_ROOT_USER")}
      MINIO_ROOT_PASSWORD: ${envRef("MINIO_ROOT_PASSWORD")}
      S3_BUCKET: ${bucket}
    entrypoint: ["/bin/sh", "-c"]
    command:
      - mc alias set stack http://minio:9000 "$$MINIO_ROOT_USER" "$$MINIO_ROOT_PASSWORD" && mc mb --ignore-existing "stack/$$S3_BUCKET"`;
}

/** The named volumes the stack keeps its data in. */
function volumes(options: StackOptions): string {
  const names = [
    ...(options.postgres ? ["db-data:"] : []),
    ...(options.storage ? ["storage-data:"] : []),
  ];
  return names.length ? `\nvolumes:\n${indent(names, 2)}\n` : "";
}

/**
 * The stack's `docker-compose.yml`: the app plus every service the options ask for, each with a
 * health check, the app waiting on them through `depends_on` conditions.
 *
 * @param options The services and secrets.
 * @param port The port the app listens on.
 * @param static_ Whether the app image is the static (file server) one.
 * @returns The file's contents.
 */
export function renderStackCompose(options: StackOptions, port: number, static_: boolean): string {
  const services = [
    webService(options, port, static_),
    ...(options.migrate ? [migrateService(options)] : []),
    ...(options.postgres ? [dbService(options)] : []),
    ...(options.storage ? [storageServices(options)] : []),
  ];
  return `${DOCKER_SENTINEL}.
# A self-hosted stack: copy .env.example to .env, fill in every secret, then
#   docker compose up -d --build
# Secrets come from .env (never commit it); a missing required one stops compose with a message.${
    options.dev ? "\n# Development: docker compose -f docker-compose.yml -f compose.dev.yml up" : ""
  }
services:
${services.join("\n\n")}
${volumes(options)}`;
}

/** Wrap `text` into `# `-prefixed comment lines of at most ~96 columns. */
function commentWrap(text: string): string[] {
  const lines: string[] = [];
  let line = "#";
  for (const word of text.split(" ")) {
    if (line.length + word.length + 1 > 96 && line !== "#") {
      lines.push(line);
      line = "#";
    }
    line += " " + word;
  }
  return [...lines, line];
}

/**
 * One `.env.example` entry: its comments, then `NAME=value`. A required secret is left EMPTY, so
 * compose refuses to start until it is filled in — a copied placeholder can never ship.
 */
function envBlock(v: StackEnvVar): string {
  const lines = commentWrap(`${v.about}${v.required ? " Required." : ""}`);
  if (v.generate) lines.push(`# Generate: ${v.generate}`);
  lines.push(`${v.name}=${v.required ? "" : v.example}`);
  return lines.join("\n");
}

/**
 * `.env.example`: every variable the stack reads, with placeholder values and how to generate
 * each secret. Copy it to `.env` (which `.dockerignore` keeps out of the image — keep it out of
 * git too).
 *
 * @param options The services and secrets.
 * @returns The file's contents.
 */
export function renderEnvExample(options: StackOptions): string {
  const blocks = stackEnv(options).map(envBlock);
  return `${DOCKER_SENTINEL}.
# Copy to .env and replace every placeholder:  cp .env.example .env
# .env holds real secrets: keep it out of git (add \`.env\` to .gitignore) — .dockerignore
# already keeps it out of the image. docker compose reads it for every service.

${blocks.join("\n\n")}
`;
}

/**
 * `compose.dev.yml`, the development overlay: the app runs `denext dev` on a bind mount of the
 * project, and Postgres and the store are published on loopback for local tools.
 *
 * @param options The services.
 * @param port The port the app listens on.
 * @returns The file's contents.
 */
export function renderComposeDev(options: StackOptions, port: number): string {
  const extra: string[] = [];
  if (options.postgres && !options.exposeDb) {
    extra.push(`  db:\n    ports:\n      - "${DB_PORT}"`);
  }
  if (options.storage) {
    extra.push(
      `  minio:\n    ports:\n      - "127.0.0.1:${ref("MINIO_PORT:-9000")}:9000"`,
    );
  }
  return `${DOCKER_SENTINEL}.
# Development overlay — on top of the production file:
#   docker compose -f docker-compose.yml -f compose.dev.yml up --build
# The app runs \`denext dev\` against a bind mount of this directory (edits reload). The dev
# server asks a non-loopback browser for its per-run token: open the URL it logs. Postgres and
# the store are published on loopback (DB_PORT / MINIO_PORT in .env move them).
# The app runs as YOUR user so it can write the bind mount — export UID and GID first
# (\`export UID GID=$(id -g)\`; both default to 1000); Deno's cache moves into .denext/ for it.
services:
  web:
    command: ["deno", "task", "dev", "--host", "0.0.0.0", "--port", "${port}"]
    user: "${ref("UID:-1000")}:${ref("GID:-1000")}"
    volumes:
      - .:/app
    environment:
      NODE_ENV: development
      DENO_DIR: /app/.denext/deno-dir${extra.length ? "\n\n" + extra.join("\n\n") : ""}
`;
}
