// The files `denext mobile add native-module --name <Name>` writes: the app's own Capacitor
// plugin (Swift + Kotlin) with one sample async method and one event, the registrars that
// register every such module with the bridge, and a typed TypeScript client usable from denext
// code and from React Native mode (`TurboModuleRegistry.getEnforcing('<Name>')` reaches the
// same plugin). The plugin and client texts ship packed in the docs-corpus pack
// (native-templates/native-module.ts is their readable source); the registrars are composed here.
//
// The generated module speaks React Native's positional convention (`nativeModule(name,
// { calls: "positional" })` in denext/mobile): a call `echo("hi")` arrives as
// `{ args: ["hi"] }`, and a result `{ value: x }` resolves to `x`. The sample reads a named
// option too (`{ message }`), which is how a plain Capacitor call passes it.
//
// The plugin and client files carry a `denext-native-module-template:` marker line: an
// unedited one is replaced by a later run, an edited one is kept. The registrars are the app's
// own files after the first run: each run only inserts a missing registration line above
// their anchor comment.

import { markedTemplateIntact, renderMarkedTemplate } from "./native-template-marker.ts";
import { NATIVE_TEMPLATES } from "./native-templates.packed.ts";
import { fillTemplate } from "./packed-text.ts";

/** The plugin and client texts (readable source: native-templates/native-module.ts). */
const TEMPLATES = NATIVE_TEMPLATES.nativeModule.NATIVE_MODULE_TEMPLATES;

/** The generation of the templates below, stamped into the files the installer writes. */
const NATIVE_MODULE_TEMPLATE_VERSION = 1;

/** The marker family of the plugin and client files. */
const FAMILY = "native-module";

/** The Kotlin Gradle plugin version the app is given (the one Capacitor 8's own plugins use). */
export const KOTLIN_VERSION = "2.2.20";

/** The Android package of the registrar and the generated plugins. */
export const NATIVE_MODULES_PACKAGE = "dev.denext.nativemodules";

/** The comment the registrars keep their registrations above. */
export const REGISTRAR_ANCHOR =
  "denext mobile add native-module adds registrations above this line.";

/**
 * A template with its marker line.
 *
 * @param template The template text.
 * @returns The file content.
 */
export function renderNativeModuleTemplate(template: string): Promise<string> {
  return renderMarkedTemplate(FAMILY, NATIVE_MODULE_TEMPLATE_VERSION, template);
}

/**
 * Whether `text` is an unedited native-module template (its marker matches its body).
 *
 * @param text A file's content.
 * @returns `true` for an intact marker.
 */
export async function isPristineNativeModuleTemplate(text: string): Promise<boolean> {
  return await markedTemplateIntact(FAMILY, text) === true;
}

/**
 * `ios/App/App/<Name>Plugin.swift`.
 *
 * @param name The module name (PascalCase).
 * @returns The Swift source (without the marker).
 */
export function swiftPlugin(name: string): string {
  return fillTemplate(TEMPLATES["Plugin.swift"], { name });
}

/**
 * `android/app/src/main/java/dev/denext/nativemodules/<Name>Plugin.kt`.
 *
 * @param name The module name (PascalCase).
 * @returns The Kotlin source (without the marker).
 */
export function kotlinPlugin(name: string): string {
  return fillTemplate(TEMPLATES["Plugin.kt"], { name, package: NATIVE_MODULES_PACKAGE });
}

/**
 * The TypeScript client, `native/Native<Name>.ts` in the app.
 *
 * @param name The module name (PascalCase).
 * @returns The TypeScript source (without the marker).
 */
export function typescriptClient(name: string): string {
  return fillTemplate(TEMPLATES["Native.ts"], { name });
}

/**
 * The iOS registrar, `ios/App/App/DenextNativeModules.swift`, registering `names`' plugins.
 *
 * @param names The module names.
 * @returns The Swift source.
 */
export function swiftRegistrar(names: readonly string[]): string {
  return `// Generated by \`denext mobile add native-module\`, which adds a line here per module. This is
// your file: register your own plugins here too. See https://denext.dev/docs/native-code.

@preconcurrency import Capacitor
import Foundation

/// Registers the app's own native modules with the bridge. \`DenextBridgeViewController\`
/// calls \`register\` from \`capacitorDidLoad()\`, before the first page loads.
@MainActor
enum DenextNativeModules {
    static func register(_ bridge: CAPBridgeProtocol?) {
${names.map(swiftRegistration).join("")}        // ${REGISTRAR_ANCHOR}
    }
}
`;
}

/** One module's line in {@linkcode swiftRegistrar}. */
export function swiftRegistration(name: string): string {
  return `        bridge?.registerPluginInstance(${name}Plugin())\n`;
}

/**
 * The Android registrar, `dev/denext/nativemodules/DenextNativeModules.java`.
 *
 * @param names The module names.
 * @returns The Java source.
 */
export function javaRegistrar(names: readonly string[]): string {
  return `// Generated by \`denext mobile add native-module\`, which adds a line here per module. This is
// your file: register your own plugins here too. See https://denext.dev/docs/native-code.

package ${NATIVE_MODULES_PACKAGE};

import com.getcapacitor.BridgeActivity;

/**
 * Registers the app's own native modules. {@code MainActivity} calls {@link #register} in
 * {@code onCreate}, before {@code super.onCreate} builds the bridge.
 */
public final class DenextNativeModules {
    private DenextNativeModules() {}

    public static void register(BridgeActivity activity) {
${names.map(javaRegistration).join("")}        // ${REGISTRAR_ANCHOR}
    }
}
`;
}

/** One module's line in {@linkcode javaRegistrar}. */
export function javaRegistration(name: string): string {
  return `        activity.registerPlugin(${name}Plugin.class);\n`;
}

/** The block appended to `android/app/build.gradle`: Kotlin compiles to the app's Java target. */
export const KOTLIN_JVM_TARGET_BLOCK = `
// denext native modules: compile Kotlin to the same JVM target as the app's Java
// (capacitor.build.gradle sets it), so the two never disagree.
tasks.withType(org.jetbrains.kotlin.gradle.tasks.KotlinCompile).configureEach {
    compilerOptions.jvmTarget = org.jetbrains.kotlin.gradle.dsl.JvmTarget.fromTarget(
        android.compileOptions.targetCompatibility.toString()
    )
}
`;
