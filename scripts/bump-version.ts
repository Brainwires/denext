#!/usr/bin/env -S deno run --allow-read --allow-write
// Bump the denext version across every "current version" spot in one shot.
//
// A version bump touches several files. This replaces the OLD version (read from the
// root deno.json "version" field, the source of truth) with a NEW one in the
// CURRENT-version spots ONLY — it never rewrites CHANGELOG release headers or README
// minimum-version prose, which are historical and must stay put.
//
//   deno task bump 2.0.0-rc.4          # apply
//   deno task bump 2.0.0-rc.4 --dry    # preview only, write nothing
//
// Spots updated (each: replace every occurrence of the old version, digit/dot-bounded
// so an embedded number is never partially rewritten):
//   - deno.json              root "version"
//   - mod.ts                 export const VERSION
//   - src/version.ts         the CLI's dependency-free copy of VERSION
//   - packages/*/deno.json   the @denext/denext peer-dependency pins (all subpaths), and the
//                            version of packages/docs-corpus, which IS denext's version
//   - deno.json              the exact `jsr:@denext/docs-corpus@<version>` import (denext X.Y.Z
//                            ships with @denext/docs-corpus X.Y.Z, rc versions included); both
//                            are set outright even when they had drifted from the old version
//   - ROADMAP.md             the "development is <version>" status line
//
// And at a STABLE release only: the prerelease specifiers the docs teach with — README.md,
// site/app/docs/**, examples/** (`jsr:@denext/denext@^4.0.0-rc.1` → `^4.0.0` when 4.0.0 ships).
// The docs may name an older rc of the same line than the one being cut (a caret on a
// prerelease admits the release), so they match any prerelease of the new version's core;
// an rc → rc bump leaves them alone.
//
// Intentionally NOT touched (printed as a reminder): CHANGELOG.md files (add a release
// section by hand), packages/*/README.md (minimum-version prose), and deno.lock
// (regenerated by Deno on the next build/cache). For a full release, also regenerate
// the API reference (`deno task docs:api`) and roll the CHANGELOG's [Unreleased]
// section — this tool deliberately stays limited to the version-string pins.

import { walk } from "@std/fs";
import { dirname, fromFileUrl, join, SEPARATOR } from "@std/path";

const ROOT = dirname(dirname(fromFileUrl(import.meta.url)));

/** A semver core with an optional prerelease/build tail (e.g. 2.0.0-rc.4, 1.4.0). */
const SEMVER_RE = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/;

/** Escape a string for literal use inside a RegExp. */
function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** A semver core with an optional prerelease/build tail. Reused by the release wrapper. */
export const VERSION_RE = SEMVER_RE;

/** The repo root (two levels up from this script). Reused by the release wrapper. */
export const REPO_ROOT = ROOT;

/** Read the current version from the root deno.json "version" field. */
export async function readCurrentVersion(): Promise<string> {
  const text = await Deno.readTextFile(join(ROOT, "deno.json"));
  const version = (JSON.parse(text) as { version?: string }).version;
  if (!version) throw new Error('root deno.json has no "version" field');
  return version;
}

/** The fixed set of files whose CURRENT-version references should be bumped. */
async function targetFiles(): Promise<string[]> {
  const files = [
    join(ROOT, "deno.json"),
    join(ROOT, "mod.ts"),
    join(ROOT, "src", "version.ts"),
    join(ROOT, "ROADMAP.md"),
  ];
  // Every packages/*/deno.json (the workspace members' peer pins).
  for await (
    const entry of walk(join(ROOT, "packages"), {
      includeDirs: false,
      match: [/packages[\\/][^\\/]+[\\/]deno\.json$/], // `\` on Windows
      maxDepth: 2,
    })
  ) {
    files.push(entry.path);
  }
  // Every examples/*/deno.json — the few that pin `jsr:@denext/denext@^<version>` (most
  // import the local checkout by relative path and are untouched by the replace).
  for await (
    const entry of walk(join(ROOT, "examples"), {
      includeDirs: false,
      match: [/examples[\\/][^\\/]+[\\/]deno\.json$/],
      maxDepth: 2,
    })
  ) {
    files.push(entry.path);
  }
  return files;
}

/** The trees whose `jsr:@denext/denext@^<core>-<pre>` specifiers a stable release rewrites. */
const DOC_SPEC_ROOTS = ["README.md", "site/app/docs", "examples"];

/** Text files a docs specifier can sit in (guides, pages, configs, CI workflows). */
const DOC_SPEC_EXTS = [".md", ".mdx", ".ts", ".tsx", ".json", ".yml", ".yaml"];

/** Never descend into installed or generated trees. */
const DOC_SPEC_SKIP = /(^|[\\/])(node_modules|\.denext|out|dist|ios|android)([\\/]|$)/;

/**
 * The docs' prerelease specifiers to rewrite for `newVersion`: `^<core>-<anything>` where
 * `<core>` is `newVersion` — only when `newVersion` is itself a stable release.
 */
export function docSpecifierPattern(newVersion: string): RegExp | null {
  if (newVersion.includes("-") || newVersion.includes("+")) return null;
  return new RegExp(
    `(?<=jsr:@denext/denext@\\^)${escapeRe(newVersion)}-[0-9A-Za-z.-]*[0-9A-Za-z]`,
    "g",
  );
}

/** Every file under {@linkcode DOC_SPEC_ROOTS}. */
async function docSpecifierFiles(): Promise<string[]> {
  const files: string[] = [];
  for (const root of DOC_SPEC_ROOTS) {
    const abs = join(ROOT, root);
    const stat = await Deno.stat(abs).catch(() => null);
    if (stat === null) continue;
    if (stat.isFile) {
      files.push(abs);
      continue;
    }
    for await (
      const entry of walk(abs, { includeDirs: false, exts: DOC_SPEC_EXTS, skip: [DOC_SPEC_SKIP] })
    ) files.push(entry.path);
  }
  return files;
}

/** The outcome of a bump: which files changed and by how much. */
export interface BumpResult {
  oldVersion: string;
  newVersion: string;
  /** Files that had at least one replacement (repo-relative path + hit count). */
  changed: { file: string; hits: number }[];
  /** Target files with no occurrence of the old version (repo-relative). */
  zeroHits: string[];
  /** Total occurrences replaced. */
  total: number;
}

/**
 * The old version as `bumpVersion` matches it: never inside a longer number (bumping
 * "2.0.0-rc.3" leaves "2.0.0-rc.30" alone, and "0.1.0" is not matched inside "10.1.0"), and
 * never as an npm dependency's own version (`npm:tus-js-client@4.3.1` is that package's, not
 * denext's — the 4.4.0 bump rewrote it to a version npm does not have).
 */
export function currentVersionPattern(oldVersion: string): RegExp {
  return new RegExp(`(?<!npm:[^"'\\s]*@[\\^~]?)(?<![\\d.])${escapeRe(oldVersion)}(?![\\d.])`, "g");
}

/**
 * Replace every current-version reference (`oldVersion` from root deno.json) with
 * `newVersion` across the fixed target-file list. Writes files unless `opts.dry`.
 * Throws if the current version already equals `newVersion`.
 */
export async function bumpVersion(
  newVersion: string,
  opts: { dry?: boolean } = {},
): Promise<BumpResult> {
  const oldVersion = await readCurrentVersion();
  if (oldVersion === newVersion) {
    throw new Error(`current version is already ${newVersion} — nothing to do`);
  }
  const re = currentVersionPattern(oldVersion);
  const results: Array<{ file: string; hits: number }> = [];
  for (const file of await targetFiles()) {
    const r = await bumpFile(file, re, newVersion, opts.dry === true);
    if (r) results.push(r);
  }
  results.push(...await syncCorpusVersion(oldVersion, newVersion, opts.dry === true));
  const docSpec = docSpecifierPattern(newVersion);
  if (docSpec) {
    const done = new Set(results.map((r) => r.file));
    for (const file of await docSpecifierFiles()) {
      if (done.has(file.slice(ROOT.length + 1).replaceAll(SEPARATOR, "/"))) continue;
      const r = await bumpFile(file, docSpec, newVersion, opts.dry === true);
      if (r && r.hits > 0) results.push(r);
    }
  }
  const changed = results.filter((r) => r.hits > 0);
  return {
    oldVersion,
    newVersion,
    changed,
    zeroHits: results.filter((r) => r.hits === 0 && !changed.some((c) => c.file === r.file))
      .map((r) => r.file),
    total: changed.reduce((n, r) => n + r.hits, 0),
  };
}

/** The docs corpus's version and denext's exact import of it (scripts/lib/docs-corpus-package.ts). */
const CORPUS_SPOTS: Array<[file: string, re: RegExp]> = [
  ["packages/docs-corpus/deno.json", /(?<="version":\s*")[^"]*(?=")/],
  ["deno.json", /(?<="jsr:@denext\/docs-corpus@)[^"]*(?=")/],
];

/**
 * Set `@denext/docs-corpus`'s version (and denext's pin of it) to `newVersion` where the
 * old-version replace did not: a spot that had drifted from `oldVersion`. One hit per spot set.
 */
async function syncCorpusVersion(
  oldVersion: string,
  newVersion: string,
  dry: boolean,
): Promise<Array<{ file: string; hits: number }>> {
  const out: Array<{ file: string; hits: number }> = [];
  for (const [file, re] of CORPUS_SPOTS) {
    const text = await readOrNull(join(ROOT, file));
    const current = text === null ? null : re.exec(text)?.[0];
    if (current === undefined) throw new Error(`${file}: no @denext/docs-corpus version to set`);
    if (current === null || current === oldVersion || current === newVersion) continue;
    if (!dry) await Deno.writeTextFile(join(ROOT, file), text!.replace(re, newVersion));
    out.push({ file, hits: 1 });
  }
  return out;
}

/** Rewrite one file; null when it does not exist in this checkout. */
async function bumpFile(
  file: string,
  re: RegExp,
  newVersion: string,
  dry: boolean,
): Promise<{ file: string; hits: number } | null> {
  const text = await readOrNull(file);
  if (text === null) return null; // a listed file may not exist in every checkout
  const hits = text.match(re)?.length ?? 0;
  if (hits > 0 && !dry) await Deno.writeTextFile(file, text.replace(re, newVersion));
  // Reported repo-relative with `/` on every OS (Windows paths carry `\\`).
  return { file: file.slice(ROOT.length + 1).replaceAll(SEPARATOR, "/"), hits };
}

async function readOrNull(file: string): Promise<string | null> {
  try {
    return await Deno.readTextFile(file);
  } catch {
    return null;
  }
}

function parseBumpArgs(): { newVersion: string; dry: boolean } {
  const dry = Deno.args.includes("--dry");
  const newVersion = Deno.args.filter((a) => a !== "--dry")[0];
  if (!newVersion) {
    console.error("usage: deno task bump <new-version> [--dry]");
    Deno.exit(2);
  }
  if (!SEMVER_RE.test(newVersion)) {
    console.error(`error: "${newVersion}" is not a valid semver (e.g. 2.0.0-rc.4)`);
    Deno.exit(2);
  }
  return { newVersion, dry };
}

export function printBumpResult(result: BumpResult, dry: boolean): void {
  console.log(
    `Bumping ${result.oldVersion} → ${result.newVersion}${dry ? "  (dry run)" : ""}\n`,
  );
  for (const { file, hits } of result.changed) console.log(bumpLine(file, hits));
  console.log(`\n${dry ? "Would change" : "Changed"} ${result.total} occurrence(s).`);
  if (result.zeroHits.length) console.log(zeroHitsNote(result.zeroHits));
  console.log(REMINDERS);
}

function bumpLine(file: string, hits: number): string {
  return `  ${file.padEnd(34)} ${hits} replacement${hits === 1 ? "" : "s"}`;
}

function zeroHitsNote(files: string[]): string {
  return `\nNote: no match in ${files.join(", ")} — expected if that file carries ` +
    `no current-version reference (or the spot moved; check by hand).`;
}

const REMINDERS = "\nReminders (not handled by this tool):\n" +
  "  • deno.lock — regenerate with a build/`deno cache` if you rely on it\n" +
  "  • CHANGELOG.md — add the release section by hand\n" +
  "  • deno task docs:api — regenerate the API reference before a release tag\n" +
  "  (or run `deno task release <version>` to do all of the above + tag)";

async function main(): Promise<void> {
  const { newVersion, dry } = parseBumpArgs();
  try {
    printBumpResult(await bumpVersion(newVersion, { dry }), dry);
  } catch (err) {
    console.error(`error: ${err instanceof Error ? err.message : err}`);
    Deno.exit(1);
  }
}

if (import.meta.main) await main();
