// Write src/gpui/props.generated.ts, `denext/gpui`'s NTB1 id table, from src/gpui/props.json: a
// byte-for-byte copy of the canonical table (thalora-web-browser `docs/b1-props.json`), which the
// gpui host's Rust table (`backends/gpui/src/protocol/props.rs`) is generated from too. Ids are
// never renumbered; a new prop is appended upstream and copied here.
//
//   deno task gen:gpui-props            # rewrite the TypeScript table
//   deno task gen:gpui-props --check    # exit 1 when it is stale or the copy was edited
//
// The copy is pinned by its SHA-256 (`CANONICAL` below). Editing src/gpui/props.json by hand fails
// here and in tests/gpui-props.test.ts: take the new table from the canonical source, then update
// `CANONICAL` (commit and hash) in the same change. Run by `deno task regen`.

import { fromFileUrl } from "@std/path";
import { encodeHex } from "@std/encoding/hex";

/** Where the table comes from, and the hash of the copy this repository holds. */
export const CANONICAL = {
  repository: "thalora-web-browser",
  path: "docs/b1-props.json",
  commit: "7debb58",
  sha256: "7c78afab74cc122eca5d51fc77d69be8d749a72833c4921c9f8c3f6fc093ea0d",
} as const;

/** The copy, repo-relative. */
export const PROPS_JSON = "src/gpui/props.json";
/** The generated table, repo-relative. */
export const PROPS_TS = "src/gpui/props.generated.ts";

const ROOT = fromFileUrl(new URL("../", import.meta.url));

/** The table's shape (b1-props.json). */
interface PropsTable {
  version: number;
  kinds: Record<string, number>;
  style: Record<string, number>;
  props: Record<string, number>;
  enums: Record<string, Record<string, number>>;
  listen: Record<string, number>;
}

/**
 * The SHA-256 of `bytes`, lower-case hex.
 *
 * @param bytes The file's bytes.
 * @returns The hash.
 */
export async function sha256Hex(bytes: Uint8Array): Promise<string> {
  return encodeHex(new Uint8Array(await crypto.subtle.digest("SHA-256", bytes as BufferSource)));
}

/** A key as an object literal writes it: bare when it is an identifier, else quoted. */
function key(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

/** `{ a: 1, … }` with one entry per line at `indent`. */
function objectLiteral(entries: Record<string, number>, indent: string): string {
  const lines = Object.entries(entries).map(([k, v]) => `${indent}  ${key(k)}: ${v},`);
  return `{\n${lines.join("\n")}\n${indent}}`;
}

/** One documented `export const` of a flat table. */
function constant(doc: string, name: string, entries: Record<string, number>): string {
  return `/** ${doc} */\nexport const ${name} = ${objectLiteral(entries, "")} as const;\n`;
}

/** The enum tables, one nested object per style prop. */
function enumsConstant(enums: Record<string, Record<string, number>>): string {
  const blocks = Object.entries(enums).map(([prop, values]) =>
    `  ${key(prop)}: ${objectLiteral(values, "  ")},`
  );
  return "/** The `u8` of each enum style value, by style prop. */\n" +
    `export const ENUM = {\n${blocks.join("\n")}\n} as const;\n`;
}

/**
 * The generated module for `table`, whose JSON copy hashes to `sha256`.
 *
 * @param table The parsed table.
 * @param sha256 The copy's SHA-256.
 * @returns The module's text.
 */
export function renderPropsModule(table: PropsTable, sha256: string): string {
  return [
    "// Generated by scripts/gen-gpui-props.ts from src/gpui/props.json. Do not edit: run\n" +
    "// `deno task gen:gpui-props`.\n" +
    `// Source: ${CANONICAL.repository} \`${CANONICAL.path}\` @ ${CANONICAL.commit}\n` +
    `// (sha256 ${sha256}).\n` +
    "// The gpui host's Rust table is generated from the same file.\n",
    "/** The NTB1 batch format version this table belongs to. */\n" +
    `export const NTB_VERSION = ${table.version};\n`,
    "/** The SHA-256 of src/gpui/props.json the table was generated from. */\n" +
    `export const PROPS_JSON_SHA256 = "${sha256}";\n`,
    constant("CREATE's node kinds.", "KIND", table.kinds),
    constant("SET_STYLE's prop ids.", "STYLE_PROP", table.style),
    constant("SET_PROP's prop ids (non-style props).", "PROP", table.props),
    enumsConstant(table.enums),
    constant("LISTEN's event mask bits.", "LISTEN", table.listen),
  ].join("\n");
}

/**
 * Read and verify the copy, and render the module.
 *
 * @param root The repository root.
 * @returns The module's text.
 * @throws {Error} When the copy's hash is not the pinned one.
 */
export async function generatePropsModule(root: string = ROOT): Promise<string> {
  const bytes = await Deno.readFile(`${root}${PROPS_JSON}`);
  const sha256 = await sha256Hex(bytes);
  if (sha256 !== CANONICAL.sha256) {
    throw new Error(
      `${PROPS_JSON} is not the pinned copy of ${CANONICAL.repository} ${CANONICAL.path} ` +
        `@ ${CANONICAL.commit} (sha256 ${sha256}, pinned ${CANONICAL.sha256}). Copy the ` +
        "canonical file verbatim and update CANONICAL in scripts/gen-gpui-props.ts.",
    );
  }
  return renderPropsModule(JSON.parse(new TextDecoder().decode(bytes)) as PropsTable, sha256);
}

if (import.meta.main) {
  const next = await generatePropsModule();
  const path = `${ROOT}${PROPS_TS}`;
  const current = await Deno.readTextFile(path).catch(() => "");
  if (Deno.args.includes("--check")) {
    if (current !== next) {
      console.error(`${PROPS_TS} is stale: run \`deno task gen:gpui-props\``);
      Deno.exit(1);
    }
    console.log(`${PROPS_TS} is current`);
  } else {
    if (current !== next) await Deno.writeTextFile(path, next);
    console.log(current === next ? `${PROPS_TS} is current` : `rewrote ${PROPS_TS}`);
  }
}
