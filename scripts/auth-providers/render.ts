/**
 * Render the generated `next-auth/providers/*` modules and the provider list from the manifest
 * `deno task gen:auth-providers` writes. Pure (no network, no `@auth/core`): the drift test
 * renders the checked-in manifest and compares the result with the checked-in modules.
 *
 * @module
 */

import type { GeneratedSpec } from "../../src/compat/next-auth/providers/generated.ts";

/** What the generator read off `@auth/core`'s providers at the pinned version. */
export interface ProviderManifest {
  /** The `@auth/core` version. */
  authjsCore: string;
  /** Every provider `@auth/core/providers/` ships (its file names), sorted. */
  all: string[];
  /** The providers written by hand. */
  handWritten: string[];
  /** The providers left out, with the reason. */
  unsupported: Record<string, string>;
  /** The generated providers: the default export's name and the spec. */
  generated: Record<string, { exportName: string; spec: GeneratedSpec }>;
}

/** The directory the provider modules live in, repo-relative. */
export const PROVIDERS_DIR = "src/compat/next-auth/providers";

/** The banner every generated file starts with. */
const BANNER = "// Generated by `deno task gen:auth-providers` from @auth/core";

/** A TypeScript identifier for an Auth.js export name (`42School` → `FortyTwoSchool`). */
function identifier(name: string): string {
  return /^[A-Za-z_$]/.test(name) ? name : `Provider${name}`;
}

/** A property key, quoted only when it is not an identifier. */
function key(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

/** A value as a TypeScript literal on one line. */
function inline(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(inline).join(", ")}]`;
  if (value && typeof value === "object") {
    const entries = Object.entries(value).map(([k, v]) => `${key(k)}: ${inline(v)}`);
    return entries.length ? `{ ${entries.join(", ")} }` : "{}";
  }
  return JSON.stringify(value);
}

/** A value as a TypeScript literal: objects to `depth` one property per line, then inline. */
function literal(value: unknown, depth: number, indent = ""): string {
  if (depth === 0 || !value || typeof value !== "object" || Array.isArray(value)) {
    return inline(value);
  }
  const inner = `${indent}  `;
  const lines = Object.entries(value).map(([k, v]) =>
    `${inner}${key(k)}: ${literal(v, depth - 1, inner)},`
  );
  return `{\n${lines.join("\n")}\n${indent}}`;
}

/** The option names a spec reads besides the credentials and the issuer. */
function extraOptions(spec: GeneratedSpec): string[] {
  const names = new Set(Object.keys(spec.options ?? {}));
  if (spec.scopeOption) names.add(spec.scopeOption);
  names.delete("issuer");
  return [...names].sort();
}

/** The module documentation for one generated provider. */
function moduleDoc(id: string, exportName: string, spec: GeneratedSpec, version: string): string {
  const env = id.toUpperCase().replace(/-/g, "_");
  const kind = spec.type === "oidc" ? "OpenID Connect" : "OAuth 2.0";
  const needsIssuer = spec.type === "oidc"
    ? spec.issuer?.includes("{issuer}") && !spec.options?.issuer
    : [spec.authorization, spec.token, spec.userinfo].some((u) => u?.includes("{issuer}")) &&
      !spec.options?.issuer;
  const issuer = needsIssuer ? ` / \`AUTH_${env}_ISSUER\`` : "";
  return [
    "/**",
    ` * \`next-auth/providers/${id}\` on denext: ${spec.name} (${kind}), generated from Auth.js's`,
    ` * own definition in \`@auth/core@${version}\`. Credentials default to \`AUTH_${env}_ID\` /`,
    ` * \`AUTH_${env}_SECRET\`${issuer}, as in Auth.js.`,
    " *",
    " * ```ts",
    ` * import ${identifier(exportName)} from "next-auth/providers/${id}";`,
    ` * export const { handlers, auth } = NextAuth({ providers: [${identifier(exportName)}] });`,
    " * ```",
    " *",
    " * @module",
    " */",
  ].join("\n");
}

/**
 * The source of one generated provider module.
 *
 * @param id The provider id (its file name).
 * @param entry The export name and spec.
 * @param version The `@auth/core` version it was read from.
 * @returns The module source.
 */
export function renderProvider(
  id: string,
  entry: { exportName: string; spec: GeneratedSpec },
  version: string,
): string {
  const name = identifier(entry.exportName);
  const profileType = `${name}Profile`;
  const extras = extraOptions(entry.spec);
  const configType = extras.length ? `${name}UserConfig` : `GeneratedUserConfig<${profileType}>`;
  const lines = [
    `${BANNER}@${version}'s providers/${id}.js — do not edit.`,
    "// fallow-ignore-file code-duplication -- generated data modules share their shape by design",
    moduleDoc(id, entry.exportName, entry.spec, version),
    "",
    "import {",
    "  generatedDescriptor,",
    "  type GeneratedSpec,",
    "  type GeneratedUserConfig,",
    '} from "./generated.ts";',
    'import type { ProviderDescriptor } from "./shared.ts";',
    "",
    `/** ${entry.spec.name}'s endpoints, scopes${
      entry.spec.profile ? " and profile mapping" : " (and Auth.js's default profile mapping)"
    }. */`,
    `const SPEC: GeneratedSpec = ${
      literal(
        entry.spec.profile ? { ...entry.spec, profile: entry.spec.profile } : entry.spec,
        2,
      )
    };`,
    "",
    `/** The ${entry.spec.name} profile, as the app's \`profile()\` callback receives it. */`,
    `export type ${profileType} = Record<string, unknown>;`,
    "",
  ];
  if (extras.length) {
    lines.push(
      `/** {@linkcode ${name}}'s options: Auth.js's, plus the ones ${entry.spec.name} reads. */`,
      `export interface ${configType} extends GeneratedUserConfig<${profileType}> {`,
    );
    for (const key of extras) {
      const fallback = entry.spec.options?.[key]?.default;
      lines.push(
        `  /** Auth.js's \`${key}\` option${
          fallback ? ` (default \`${fallback.replace(/`/g, "")}\`)` : ""
        }. */`,
        `  ${key}?: string;`,
      );
    }
    lines.push("}", "");
  }
  lines.push(
    "/**",
    ` * The ${entry.spec.name} provider.`,
    " *",
    " * @param options Client credentials (default from the environment), an `id` / `name`",
    " *   override, `authorization.params`, a `profile()` mapper.",
    " * @returns The provider descriptor for `NextAuth({ providers })`.",
    " */",
    `export default function ${name}(`,
    `  options: ${configType} = {},`,
    `): ProviderDescriptor<${configType}> {`,
    "  return generatedDescriptor(SPEC, options);",
    "}",
    "",
  );
  return lines.join("\n");
}

/**
 * Every provider module the shim ships (hand-written and generated), sorted.
 *
 * @param manifest The manifest.
 * @returns The module names.
 */
export function providerModules(manifest: ProviderManifest): string[] {
  return [...manifest.handWritten, ...Object.keys(manifest.generated)].sort();
}

/**
 * The source of `providers/list.ts`: the module names, for the build's alias lists.
 *
 * @param manifest The manifest.
 * @returns The module source.
 */
export function renderList(manifest: ProviderManifest): string {
  const names = providerModules(manifest).map((n) => `  ${JSON.stringify(n)},`).join("\n");
  return [
    `${BANNER}@${manifest.authjsCore} — do not edit.`,
    "/**",
    " * The `next-auth/providers/*` modules denext's shim ships, hand-written and generated: the",
    " * compat build keeps them external and `denext migrate` maps them.",
    " *",
    " * @module",
    " */",
    "",
    "/** The provider module names (`next-auth/providers/<name>`). */",
    "export const NEXT_AUTH_PROVIDER_MODULES: readonly string[] = [",
    names,
    "];",
    "",
  ].join("\n");
}

/**
 * Every file the manifest renders, repo-relative path → source.
 *
 * @param manifest The manifest.
 * @returns The files.
 */
export function renderAll(manifest: ProviderManifest): Map<string, string> {
  const files = new Map<string, string>();
  for (const [id, entry] of Object.entries(manifest.generated)) {
    files.set(`${PROVIDERS_DIR}/${id}.ts`, renderProvider(id, entry, manifest.authjsCore));
  }
  files.set(`${PROVIDERS_DIR}/list.ts`, renderList(manifest));
  return files;
}
