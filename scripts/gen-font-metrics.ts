// Regenerate `src/compat/next/font/font-metrics.ts` — the vertical metrics + average glyph
// width of every Google Fonts family (and the two local fallback faces, Arial and Times New
// Roman), which `next/font`'s `adjustFontFallback` needs to emit a metric-matched fallback
// `@font-face` (`size-adjust` / `ascent-override` / `descent-override` / `line-gap-override`).
//
// The data is Capsize's font-metrics set (seek-oss/capsize, MIT), in the compiled form Next
// ships as `next/dist/server/capsize-font-metrics.json`, so denext computes the SAME overrides
// Next does for the same family. A guessed table would mis-size the fallback; this one is real.
//
//   deno task gen:font-metrics -- --from <path/to/capsize-font-metrics.json>   # a local Next
//   deno task gen:font-metrics                                                 # fetch from the npm CDN
//
// The output is sorted and deterministic; commit it.

import { fromFileUrl } from "@std/path";

const OUT = fromFileUrl(new URL("../src/compat/next/font/font-metrics.ts", import.meta.url));
const CDN = "https://cdn.jsdelivr.net/npm/next@16/dist/server/capsize-font-metrics.json";

/** One family's entry in Capsize's set (the fields the override math reads). */
interface CapsizeEntry {
  familyName: string;
  category: string;
  ascent: number;
  descent: number;
  lineGap: number;
  unitsPerEm: number;
  xWidthAvg: number;
}

/** The compact tuple the generated table stores per family. */
export type MetricsTuple = [
  family: string,
  category: string,
  unitsPerEm: number,
  ascent: number,
  descent: number,
  lineGap: number,
  xWidthAvg: number,
];

async function loadCapsize(path: string | null): Promise<Record<string, CapsizeEntry>> {
  if (path) return JSON.parse(await Deno.readTextFile(path));
  const res = await fetch(CDN);
  if (!res.ok) throw new Error(`${CDN}: HTTP ${res.status}`);
  return await res.json();
}

/** Whether a Capsize entry carries the fields the override math reads. */
function usable(e: CapsizeEntry | undefined): e is CapsizeEntry {
  return typeof e?.familyName === "string" && e.unitsPerEm > 0;
}

/** Tuples for every family with the fields the math needs, sorted by family name. */
export function toTuples(data: Record<string, CapsizeEntry>): MetricsTuple[] {
  return Object.values(data)
    .filter(usable)
    .map((e): MetricsTuple => [
      e.familyName,
      e.category,
      e.unitsPerEm,
      e.ascent,
      e.descent,
      e.lineGap,
      e.xWidthAvg,
    ])
    .sort((a, b) => a[0].localeCompare(b[0], "en"));
}

/** The categories, by their index in a row (rows store the index, not the name). */
const CATEGORIES = ["sans-serif", "serif", "display", "handwriting", "monospace"];

/** Up to how many leading characters a row shares with the previous family (one digit). */
const MAX_SHARED = 9;

/**
 * The generated module: one line per family in a string, parsed once at load. A line is the
 * number of leading characters its family shares with the previous line's (one digit, 0–9), the
 * rest of the family, then `|category index|unitsPerEm|ascent|descent|lineGap|xWidthAvg` in base
 * 36, or nothing when those six equal the previous line's. Plain text, not Brotli: `next/font`
 * can run in a browser bundle, which has no `node:zlib`. A third of the size of the rows written
 * out in decimal, which counted against the JSR package's size cap.
 */
export function render(rows: MetricsTuple[]): string {
  let previous = "";
  let previousNums = "";
  const lines = rows.map(([family, category, ...nums]) => {
    const at = CATEGORIES.indexOf(category);
    if (at < 0) throw new Error(`gen-font-metrics: unknown category ${category} (${family})`);
    if (/[|\n`\\$]/.test(family)) throw new Error(`gen-font-metrics: unsafe family ${family}`);
    if (!nums.every(Number.isSafeInteger)) {
      throw new Error(`gen-font-metrics: non-integer metrics for ${family}`);
    }
    let shared = 0;
    while (
      shared < MAX_SHARED && shared < family.length && family[shared] === previous[shared]
    ) shared++;
    const values = [at, ...nums].map((n) => n.toString(36)).join("|");
    const line = `${shared}${family.slice(shared)}${values === previousNums ? "" : `|${values}`}`;
    previous = family;
    previousNums = values;
    return line;
  });
  return `// GENERATED by scripts/gen-font-metrics.ts — do not edit by hand.
// Capsize font metrics (seek-oss/capsize, MIT; the set Next ships as
// next/dist/server/capsize-font-metrics.json) for ${rows.length} families, incl. the local
// fallback faces Arial and Times New Roman. One line per family: how many leading characters it
// shares with the previous line's family (one digit), the rest of its name, then
// |category|unitsPerEm|ascent|descent|lineGap|xWidthAvg in base 36 (the category an index into
// CATEGORIES), left out when they equal the previous line's. Read by
// src/compat/next/font/fallback.ts.

const CATEGORIES = [${CATEGORIES.map((c) => JSON.stringify(c)).join(", ")}];

const ROWS = \`${lines.join("\n")}\`;

let family = "";
let values: number[] = [];

/** \`[family, category, unitsPerEm, ascent, descent, lineGap, xWidthAvg]\` per family. */
export const FONT_METRICS: readonly (readonly [
  string,
  string,
  number,
  number,
  number,
  number,
  number,
])[] = ROWS.split("\\n").map((line) => {
  const [name, ...nums] = line.split("|");
  family = family.slice(0, Number(name[0])) + name.slice(1);
  if (nums.length > 0) values = nums.map((n) => parseInt(n, 36));
  const [category, unitsPerEm, ascent, descent, lineGap, xWidthAvg] = values;
  return [family, CATEGORIES[category], unitsPerEm, ascent, descent, lineGap, xWidthAvg];
});
`;
}

if (import.meta.main) {
  const fromIdx = Deno.args.indexOf("--from");
  const data = await loadCapsize(fromIdx >= 0 ? Deno.args[fromIdx + 1] : null);
  const rows = toTuples(data);
  await Deno.writeTextFile(OUT, render(rows));
  console.log(`wrote ${OUT} (${rows.length} families)`);
}
