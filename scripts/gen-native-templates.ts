// Generate the packed native templates: every native template record the readable sources under
// src/build/native-templates/ export (Swift, Java, Kotlin and XML texts that `denext mobile add …`
// writes into a Capacitor project), packed into one Brotli-compressed JSON document in base64 that
// the published `src/build/*-native-templates.ts` modules read through `packedRecords`
// (src/build/packed-text.ts). The sources stay in the repo, out of the JSR package (deno.json
// `publish.exclude`): packed, the templates are a quarter of their size. The pack itself ships in
// `@denext/docs-corpus` (packages/docs-corpus/native-templates.ts), which denext pins at exactly
// its own version, to keep it out of the 20 MiB @denext/denext package; the layout (each record's
// keys) stays in src/build/native-templates.packed.ts, which loads the pack: from the same
// checkout when denext runs from one, so a checkout never waits on a docs-corpus release.
//
//   deno task gen:native-templates
//
// tests/native-templates-packed.test.ts fails while the packed texts differ from the sources.
// A new source module is a new group: add its file here (the published module that reads it
// imports `NATIVE_TEMPLATES.<group>`, so generate before that module is first imported).

import { fromFileUrl, join, relative, toFileUrl } from "@std/path";
import { denoFmt } from "./lib/deno-fmt.ts";
import { packTexts, type TextGroups } from "./lib/pack-texts.ts";

const ROOT = fromFileUrl(new URL("..", import.meta.url));
/** The readable sources, one group per file. */
export const SOURCES_DIR: string = join(ROOT, "src", "build", "native-templates");
/** Where the module that lays the records out (and imports the pack) is written. */
export const PACKED_OUT: string = join(ROOT, "src", "build", "native-templates.packed.ts");
/** Where the pack is written: a module of `@denext/docs-corpus`. */
export const PACK_OUT: string = join(ROOT, "packages", "docs-corpus", "native-templates.ts");

/** `ota-native` → `otaNative`: a group name from a source file's base name. */
export function groupName(file: string): string {
  return file.replace(/\.ts$/, "").replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
}

/** Every source module's exported records, by group (sorted by file name). */
export async function templateGroups(): Promise<TextGroups> {
  const files = [...Deno.readDirSync(SOURCES_DIR)]
    .filter((e) => e.isFile && e.name.endsWith(".ts"))
    .map((e) => e.name)
    .sort();
  const groups: TextGroups = {};
  for (const file of files) {
    const mod = await import(toFileUrl(join(SOURCES_DIR, file)).href);
    groups[groupName(file)] = Object.fromEntries(
      Object.entries(mod).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0),
    ) as Record<string, Record<string, string>>;
  }
  return groups;
}

/** The two modules' sources: the layout (and loader) in denext, the pack in `@denext/docs-corpus`. */
export async function generate(): Promise<{ text: string; pack: string; bytes: number }> {
  const { layout, packed, bytes } = packTexts(await templateGroups());
  const text = await denoFmt(
    `// Generated by \`deno task gen:native-templates\` (scripts/gen-native-templates.ts). Do not edit:
// the templates' readable sources are src/build/native-templates/*.ts (not published). Their
// records as Brotli-compressed JSON in base64, decoded on first read (src/build/packed-text.ts).
// The pack ships in @denext/docs-corpus (packages/docs-corpus/native-templates.ts), out of the
// 20 MiB @denext/denext package; this module loads it and lays its records out.

import { checkoutFile } from "./checkout-file.ts";
import { packedRecords } from "./packed-text.ts";

/**
 * The pack's module. From a published @denext/denext, \`@denext/docs-corpus\` at exactly denext's
 * version (every release publishes it first). From a checkout — the repository, a checkout an app
 * links by path, a \`deno compile\` binary built from one — the same commit's file, read by path:
 * the docs-corpus release with that commit's pack may not exist yet, or be younger than Deno's
 * minimum dependency age. A vendored copy (\`"vendor": true\`) is \`file:\` too but no checkout: it
 * imports the package, as published.
 */
const local = checkoutFile("../../packages/docs-corpus/native-templates.ts", import.meta.url);
const pack: { NATIVE_TEMPLATES_BROTLI_BASE64: string } = local
  ? await import(local)
  : await import("@denext/docs-corpus/native-templates");

/** Every native template record, by source module and export name. */
export const NATIVE_TEMPLATES = packedRecords(
  ${JSON.stringify(layout)},
  pack.NATIVE_TEMPLATES_BROTLI_BASE64,
);
`,
    ROOT,
  );
  const pack =
    `// Generated by \`deno task gen:native-templates\` (scripts/gen-native-templates.ts in the denext
// repository). Do not edit.

/**
 * The native templates \`denext mobile add …\` writes into a Capacitor project (Swift, Java, Kotlin
 * and XML), as Brotli-compressed JSON in base64. \`@denext/denext\` lays the records out and
 * decodes them on first read (\`src/build/native-templates.packed.ts\`).
 *
 * @module
 */

/** The native template records, Brotli-compressed JSON, base64. */
export const NATIVE_TEMPLATES_BROTLI_BASE64: string =
  ${JSON.stringify(packed)};
`;
  return { text, pack, bytes };
}

if (import.meta.main) {
  const { text, pack, bytes } = await generate();
  await Deno.writeTextFile(PACKED_OUT, text);
  await Deno.writeTextFile(PACK_OUT, pack);
  console.log(
    `wrote ${relative(ROOT, PACKED_OUT)} + ${relative(ROOT, PACK_OUT)}: ${
      (bytes / 1024).toFixed(0)
    } KiB of templates, ${(pack.length / 1024).toFixed(0)} KiB packed`,
  );
}
