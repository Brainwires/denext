// Generate src/build/native-templates.packed.ts: every native template record the readable
// sources under src/build/native-templates/ export (Swift, Java, Kotlin and XML texts that
// `denext mobile add …` writes into a Capacitor project), packed into one Brotli-compressed JSON
// document in base64 that the published `src/build/*-native-templates.ts` modules read through
// `packedRecords` (src/build/packed-text.ts). The sources stay in the repo, out of the JSR
// package (deno.json `publish.exclude`): packed, the templates are a quarter of their size.
//
//   deno task gen:native-templates
//
// tests/native-templates-packed.test.ts fails while the packed texts differ from the sources.
// A new source module is a new group: add its file here (the published module that reads it
// imports `NATIVE_TEMPLATES.<group>`, so generate before that module is first imported).

import { fromFileUrl, join, relative, toFileUrl } from "@std/path";
import { denoFmt } from "./lib/deno-fmt.ts";
import { packTexts, type TextGroups } from "./lib/pack-texts.ts";

const ROOT = fromFileUrl(new URL("..", import.meta.url));
/** The readable sources, one group per file. */
export const SOURCES_DIR: string = join(ROOT, "src", "build", "native-templates");
/** Where the packed module is written. */
export const PACKED_OUT: string = join(ROOT, "src", "build", "native-templates.packed.ts");

/** `ota-native` → `otaNative`: a group name from a source file's base name. */
export function groupName(file: string): string {
  return file.replace(/\.ts$/, "").replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
}

/** Every source module's exported records, by group (sorted by file name). */
export async function templateGroups(): Promise<TextGroups> {
  const files = [...Deno.readDirSync(SOURCES_DIR)]
    .filter((e) => e.isFile && e.name.endsWith(".ts"))
    .map((e) => e.name)
    .sort();
  const groups: TextGroups = {};
  for (const file of files) {
    const mod = await import(toFileUrl(join(SOURCES_DIR, file)).href);
    groups[groupName(file)] = Object.fromEntries(
      Object.entries(mod).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0),
    ) as Record<string, Record<string, string>>;
  }
  return groups;
}

/** The packed module's source. */
export async function generate(): Promise<{ text: string; bytes: number }> {
  const { layout, packed, bytes } = packTexts(await templateGroups());
  const text = await denoFmt(
    `// Generated by \`deno task gen:native-templates\` (scripts/gen-native-templates.ts). Do not edit:
// the templates' readable sources are src/build/native-templates/*.ts (not published). Their
// records as Brotli-compressed JSON in base64, decoded on first read (src/build/packed-text.ts).

import { packedRecords } from "./packed-text.ts";

/** Every native template record, by source module and export name. */
export const NATIVE_TEMPLATES = packedRecords(
  ${JSON.stringify(layout)},
  ${JSON.stringify(packed)},
);
`,
    ROOT,
  );
  return { text, bytes };
}

if (import.meta.main) {
  const { text, bytes } = await generate();
  await Deno.writeTextFile(PACKED_OUT, text);
  console.log(
    `wrote ${relative(ROOT, PACKED_OUT)}: ${(bytes / 1024).toFixed(0)} KiB of templates, ${
      (text.length / 1024).toFixed(0)
    } KiB packed`,
  );
}
